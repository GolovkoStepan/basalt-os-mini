const uint8_t* font_glyph(uint32_t cp)
{
    if (cp >= FONT_ASCII_FIRST && cp <= FONT_ASCII_LAST) {
        return kAscii[cp - FONT_ASCII_FIRST];
    }
    if (cp >= FONT_CYR_FIRST && cp <= FONT_CYR_LAST) {
        return kCyr[cp - FONT_CYR_FIRST];
    }
    if (cp == 0x0401) {
        return kYoUpper[0];
    }
    if (cp == 0x0451) {
        return kYoLower[0];
    }
    return NULL;
}
