// Текстовая матрица: символы в клетках, курсор, прокрутка.
//
// Зачем отдельный слой, а не рисование прямо в драйвер экрана. Драйвер знает
// про линии, такты и окна панели; текст знает про символы, строки и клетки.
// Если смешать это в одном файле, то первая же смена панели (а на P4 будет
// другая) потянет переписывание логики вывода. Здесь наоборот: матрица не
// знает ни одного регистра и даже не знает, что такое экран, - она отдаёт
// готовые пиксели полосы, а кто их передаёт, решает вызывающий.
//
// Цена такой границы: вызывающий обязан сам звать text_render_row и передавать
// полосу драйверу. Это ровно одна функция на строку в одном месте - в обмен на
// то, что вся логика текста проверяется на маке, без платы.
//
// Геометрия и почему именно такая. Панель 320x170. Клетка 6x10 пикселей:
// глиф 5x7 плюс по пикселю справа и снизу. 53 клетки по 6 = 318, ещё по
// пикселю поля слева и справа - ровно 320. 17 строк по 10 = ровно 170.
// Числа сходятся без остатка, поэтому 53x17 - не «сколько влезло», а следствие
// выбранной клетки.
//
// Клетка хранит code point (16 бит), а не байт: в байт влезает только ASCII,
// и «Ж» пришлось бы хранить двумя клетками. Кириллица в UTF-8 занимает два
// байта, но один code point, и в клетке ей место одно.

#pragma once

#include <stdbool.h>
#include <stdint.h>

#define TEXT_COLS     53
#define TEXT_ROWS     17

// Клетка и глиф внутри неё. Глиф прижат к верху клетки и сдвинут на пиксель
// вниз: тогда под ним остаются две свободные строки пикселей - там рисуется
// курсор, не закрывая саму букву.
#define TEXT_CELL_W   6
#define TEXT_CELL_H   10
#define TEXT_GLYPH_W  5
#define TEXT_GLYPH_H  7
#define TEXT_GLYPH_DY 1

// Поле слева и справа. Нужно не для красоты: без него последний столбец
// символов упирается в самый край панели, а первый начинается с нулевого
// пикселя, где край экрана часто срезан корпусом.
#define TEXT_MARGIN_X 1

// Ширина полосы в пикселях и её размер в словах RGB565. Столько пишет
// text_render_row и столько же читает драйвер, поэтому размер один на оба.
#define TEXT_STRIP_W      (TEXT_COLS * TEXT_CELL_W + 2 * TEXT_MARGIN_X)
#define TEXT_STRIP_PIXELS (TEXT_STRIP_W * TEXT_CELL_H)

// Сбросить матрицу: пустые клетки, курсор в левый верхний угол, все строки
// помечены как изменённые (после сброса экран не совпадает с матрицей).
void text_init(void);

// То же, что text_init, но без сброса цветов: очистить экран.
void text_clear(void);

// Цвета: текст и фон в RGB565. Смена цвета помечает все строки изменёнными -
// иначе на экране осталась бы смесь старых и новых цветов.
void text_set_colors(uint16_t fg, uint16_t bg);

// Положить символ в позицию курсора и сдвинуть курсор. Понимает \n, \r, \b и
// \t. Байты старше 0x7F собираются в UTF-8 code point: кириллица занимает два
// байта, и её граница может попасть на границу двух вызовов. Символ, для
// которого нет глифа, рисуется как '?', а не пропускается: пустая клетка
// выглядела бы как пропавшая буква при целом потоке.
void text_putc(char c);

void text_puts(const char* s);

// То же, но code point уже собран. Нужно там, где символ пришёл не байтами
// потока: разбор escape-последовательности (A2) знает код сразу, и гонять
// его через декодер обратно в байты незачем.
void text_put_cp(uint32_t cp);

// Позиция курсора. За пределами матрицы не бывает: вывод за последнюю строку
// прокручивает экран.
void text_cursor_at(int col, int row);
int text_cursor_col(void);
int text_cursor_row(void);

// Курсор рисуется подчёркиванием под клеткой. Мигание - снаружи, по тику:
// у матрицы нет часов, и заводить их внутри значило бы завести второй
// источник времени рядом с basalt_uptime_us.
void text_cursor_blink(bool visible);
bool text_cursor_visible(void);

// Изменилась ли строка с прошлой отрисовки. Приложение проходит по этим
// флагам и передаёт только изменившиеся строки - в этом смысл dirty-строк:
// полная перерисовка стоит десятков миллисекунд, строка - около двух.
bool text_row_dirty(int row);
void text_row_clean(int row);

// Нарисовать строку в буфер из TEXT_STRIP_PIXELS слов RGB565. Функция только
// читает матрицу, флаг изменённости не снимает: снимает его тот, кто отправил
// полосу в драйвер (text_row_clean). Так неудачная передача не теряет
// изменений.
void text_render_row(int row, uint16_t* dst);
