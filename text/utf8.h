// Декодер UTF-8: байты потока -> code point.
//
// Зачем отдельный модуль, а не разбор внутри матрицы. Экран принимает байты
// из USB, а кириллица в UTF-8 занимает два байта, и граница символа может
// попасть на границу двух вызовов text_putc. Значит состояние «сколько байт
// ещё ждём» должно жить где-то между вызовами - и это состояние проще
// проверить на маке, чем на плате, где видно только «буква не та».
//
// Модуль ничего не знает ни про экран, ни про шрифт: он отдаёт числа.

#pragma once

#include <stdint.h>

// Состояние разбора. Одно на поток; лежит у вызывающего, а не внутри модуля:
// два потока (экран и консоль) не должны делить одну недособранную букву.
typedef struct {
    uint32_t cp;    // накопленные биты code point
    uint32_t min;   // минимальное допустимое значение - защита от overlong
    int need;       // сколько байт-продолжений ещё ждём
} utf8_decoder;

typedef enum {
    // Байт принят, символ ещё не собран: ждём продолжение.
    UTF8_PENDING = 0,
    // Символ собран, *out заполнен.
    UTF8_DONE = 1,
    // Байт отвергнут, состояние сброшено. Курсор двигать не надо.
    UTF8_INVALID = -1,
} utf8_status;

// Сбросить состояние. Нужно перед новым потоком и после управляющего байта:
// команда означает, что поток вернулся к началу и недособранная буква уже
// не продолжится.
void utf8_reset(utf8_decoder* d);

// Скормить один байт. ASCII (0x00..0x7F) тоже проходит через декодер и
// возвращается как UTF8_DONE: так вызывающему не нужно разбирать два случая.
//
// Что отвергается (UTF8_INVALID): байт-продолжение без головки, головка
// 0xC0/0xC1 и 0xF5..0xFF, overlong-запись, суррогаты 0xD800..0xDFFF,
// значения больше 0x10FFFF. Всё это - не символы, и рисовать вместо них
// заглушку значило бы показывать мусор на каждый сбойный байт.
utf8_status utf8_feed(utf8_decoder* d, uint8_t byte, uint32_t* out);
