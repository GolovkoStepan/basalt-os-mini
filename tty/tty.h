// Line discipline: буфер строки и превращение нажатий в события.
//
// Зачем отдельный слой, а не разбор прямо в цикле чтения USB. У терминала две
// разные жизни: в каноническом режиме программа получает строку целиком, а
// стереть символ и «сходить в историю» делает сам терминал; в raw-режиме
// наоборот - каждый байт уходит программе сразу, и терминал не вмешивается.
// Если это смешать с чтением порта, то первая же программа вроде редактора
// потребует правок в драйвере USB, хотя ей нужен только другой режим.
//
// Граница проведена так: tty не знает ни про экран, ни про USB. Он принимает
// байты и отдаёт события - что нарисовать и что отдать программе. Рисует и
// отдаёт вызывающий. Поэтому вся логика набора проверяется на маке: тест
// кормит байты и смотрит события.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "utf8.h"

// Предел строки. Не TEXT_COLS: строка может быть длиннее экрана, его
// прокрутит матрица. 256 - компромисс: под команду шелла хватает с запасом,
// а буфер остаётся в SRAM и не требует кучи.
#define TTY_LINE_CAP 256

typedef enum {
    TTY_MODE_CANON = 0,  // построчно: строка отдаётся по Enter
    TTY_MODE_RAW = 1,    // побайтно: отдаётся сразу всё, включая управляющие
} tty_mode;

typedef enum {
    // Ничего не произошло: байт накоплен, но ни символа, ни строки пока нет
    // (например, первый байт двухбайтовой буквы).
    TTY_EV_NONE = 0,

    // Нарисовать символ cp. В каноническом режиме это эхо, в raw - данные:
    // raw-режим отличает данные от эха тем, что эха в нём нет вовсе.
    TTY_EV_CHAR,

    // Стереть последний нарисованный символ. Именно символ, а не байт: «Ж»
    // занимает два байта в строке, но одну клетку на экране.
    TTY_EV_ERASE,

    // Строка готова, текст - в tty_line(). В raw-режиме не бывает: там строк
    // нет по определению.
    TTY_EV_LINE,

    // Ctrl-C: прервать ввод, буфер выбросить.
    TTY_EV_INTR,

    // Ctrl-D на пустой строке: конец ввода.
    TTY_EV_EOF,

    // Стирать нечего: Backspace в начале строки. Вызывающий может пикнуть,
    // но ничего не обязан делать - это подсказка, а не команда.
    TTY_EV_BELL,
} tty_event;

typedef struct {
    tty_event event;
    uint32_t cp;  // заполняется только для TTY_EV_CHAR
} tty_result;

// Сбросить всё: пустая строка, канонический режим, позиция курсора в начале.
// Нужно при старте и при переключении режима - иначе недособранная строка
// из прошлого режима попадёт в новый.
void tty_init(void);

void tty_set_mode(tty_mode mode);
tty_mode tty_mode_get(void);

// Скормить один принятый байт. Возвращает событие для вызывающего.
tty_result tty_input(uint8_t byte);

// Готовая строка (без завершающего \r\n). Годна до следующего tty_input.
// Возвращает пустую строку, если строки нет.
const char* tty_line(void);

// Длина готовой строки в байтах.
size_t tty_line_len(void);

// Текущее содержимое буфера строки: то, что набрано, и (до следующего
// tty_input) готовая строка после TTY_EV_LINE. Читать буфер напрямую нельзя -
// иначе вызывающий начнёт зависеть от его устройства.
const char* tty_pending(void);
size_t tty_pending_len(void);

