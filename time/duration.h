// Длительности: разбор "500ms", "2s", "1m30s", "1h" и печать обратно.
//
// Зачем отдельный модуль. Разбор длительности кажется однострочником, пока не
// понадобится "1m30s", и тогда выясняется, что «1m30» - это опечатка, а не
// 30 секунд, и что «0» надо отличать от «0s». На плате такая ошибка выглядит
// как команда, которая молча ничего не делает или ждёт вечность, а на маке
// проверяется таблицей. Порог и точность здесь - миллисекунды: тик у нас
// микросекундный, но планировщика нет, и ждать точнее миллисекунды бессмысленно.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Больше суток одной командой не ждём: это уже не `sleep`, а забытая команда
// в /etc/rc, и вешать систему при старте нельзя.
#define DURATION_MAX_MS (24u * 3600u * 1000u)

// Разобрать длительность в миллисекунды.
//
// Формы: "300" - секунды (как у обычного sleep), "300ms", "5s", "2m",
// "1h", а также составная "1m30s". Секунды по умолчанию, а не миллисекунды,
// потому что `sleep 5` должен значить пять секунд, как везде.
//
// false - синтаксис не тот, значение ноль или больше суток. Ноль отвергается
// намеренно: `sleep 0` почти всегда опечатка (`sleep 0.5` без дробной части),
// и лучше сказать об этом, чем вернуться мгновенно.
bool duration_parse(const char* text, uint32_t* out_ms);

// Печать: "1 ч 30 мин", "250 мс", "3 с". Нужно, чтобы `sleep` сказал, сколько
// он на самом деле проспал, а `alarm` - сколько осталось.
const char* duration_text(char* buf, size_t cap, uint32_t ms);
