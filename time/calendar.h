// Календарь: секунды Unix в дату и обратно, разбор и печать.
//
// Зачем отдельный модуль. Перевод «секунды с 1970-го» в год-месяц-день - это
// десяток строк арифметики, в которых ошибаются все: то 1900-й не високосный,
// то февраль в 2000-м, то день недели съезжает на единицу. На плате такая
// ошибка выглядит как «дата врёт на день» и замечается через неделю, а на маке
// проверяется таблицей дат за секунду. Поэтому здесь чистая логика, без часов,
// без VFS и без экрана: на вход число, на выход строка или наоборот.
//
// Часы (то есть «сколько сейчас») живут в time/clock.c: у них есть состояние,
// которое этот модуль трогать не должен.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Буфер под полную дату с секундами: "2026-11-07 18:42:03" и ноль.
#define CAL_TEXT_MAX 20

// Разобранная дата. Год - обычное число (2026), а не «годы от 1900»: у нас
// нет причин наследовать эту привычку C.
typedef struct {
    int year;
    int month;  // 1..12
    int day;    // 1..31
    int hour;   // 0..23
    int min;    // 0..59
    int sec;    // 0..59
    int wday;   // 0 - понедельник ... 6 - воскресенье
} cal_t;

// Разложить секунды Unix. Для 0 получится 1970-01-01 00:00:00 (четверг).
void cal_from_unix(uint32_t unix_secs, cal_t* out);

// Собрать секунды Unix. false - дата не существует (31 февраля, 25 часов,
// год за пределами 1970..2106): молча подставить соседний день хуже, чем
// отказать, потому что опечатку в команде тогда никто не увидит.
bool cal_to_unix(const cal_t* t, uint32_t* out);

// День недели: 0 - понедельник. Короткое русское имя для печати.
int cal_weekday(uint32_t unix_secs);
const char* cal_weekday_short(int wday);

// Печать даты. Возвращают buf, чтобы вызов можно было вложить в out_puts -
// так же, как basalt_format_u64. Если cap мало, строка обрезается, но всегда
// завершается нулём; полная дата требует CAL_TEXT_MAX.
const char* cal_text(char* buf, size_t cap, uint32_t unix_secs);        // 2026-11-07 18:42:03
const char* cal_text_iso(char* buf, size_t cap, uint32_t unix_secs);    // 2026-11-07T18:42:03
const char* cal_text_short(char* buf, size_t cap, uint32_t unix_secs);  // 07.11 18:42

// Разобрать дату из текста. Понимает "2026-11-07T18:42", с пробелом вместо
// T, с секундами и без, и с переводом строки в конце - файл /etc/clock
// читается построчно, и хвост \r\n не должен превращать дату в мусор.
// Причина одна на всё: этот же разбор нужен команде `date` и загрузке
// сохранённого времени при старте.
bool cal_parse(const char* text, uint32_t* unix_secs);
