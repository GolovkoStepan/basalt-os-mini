// Часы: «сколько сейчас» на основе монотонного счётчика.
//
// Зачем отдельный модуль, если календарь уже есть. Календарь умеет переводить
// число в дату и обратно, но не знает, какое число сейчас. Часы знают ровно
// две вещи: точку отсчёта (секунды Unix в момент установки) и показание
// монотонного счётчика в тот же момент. Текущее время - это точка плюс
// прошедшее с тех пор, поэтому часы не отстают и не «тикают» отдельно от
// таймера: второго источника времени в системе нет.
//
// Почему не RTC-периферия чипа. У ESP32-S3 есть RTC-домен, который считает
// время при выключенном питании, но у платы нет батарейки на VBAT - при
// отключении USB RTC сбрасывается вместе со всей памятью домена. То есть
// преимущества перед обычным счётчиком нет, а неочевидного кода с регистрами
// RTC и его медленными часами (150 кГц) - много.
//
// Отсюда устройство времени в системе:
//
//   - при старте часы не установлены, и это видно (`clock_synced`), а не
//     маскируется нулём: 1970-й год на экране читался бы как рабочая дата;
//   - время устанавливает человек командой `date set ...` или (позже) NTP;
//   - установленное время хранится в /etc/clock, и при старте часы получают
//     его как «время последнего включения» - дата после перезагрузки остаётся
//     правдоподобной, хотя и отстаёт на время, пока плата была выключена.
//
// Модуль переносимый: ни регистров, ни VFS, поэтому проверяется на маке.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

typedef struct {
    uint32_t base_unix;  // секунды Unix в момент установки
    uint64_t base_mono;  // basalt_uptime_us() в тот же момент
    bool synced;         // время когда-нибудь устанавливали
} clock_t;

void clock_reset(clock_t* c);

// Установить время. mono_us - текущее показание монотонного счётчика: часы
// не читают его сами, иначе модуль перестал бы собираться на маке.
void clock_set(clock_t* c, uint32_t unix_secs, uint64_t mono_us);

bool clock_synced(const clock_t* c);

// Текущее время. false - часы не установлены, и *out не тронут: вызывающий
// решает, что показать вместо даты, а не получает 1970-й год.
bool clock_now(const clock_t* c, uint64_t mono_us, uint32_t* out);

// Сколько секунд прошло с установки. Нужно, чтобы `date` показывал, откуда
// время: установлено вручную сейчас или поднято из /etc/clock при старте.
uint32_t clock_age_secs(const clock_t* c, uint64_t mono_us);
