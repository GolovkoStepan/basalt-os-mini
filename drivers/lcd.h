// Экран: то, что нужно ОС, а не конкретной панели.
//
// Зачем свой интерфейс. У плат разная шина: на T-Display-S3 панель висит на
// 8-битной параллельной шине, на Cardputer - на SPI. Код выше (текстовая
// матрица, курсор, прокрутка) не должен об этом знать: он просит «залей
// прямоугольник», а как именно байты поедут к панели, решает реализация,
// выбранная сборкой (src/CMakeLists.txt). Поэтому здесь только три вещи,
// которые нужны любому экрану, и ни одного регистра.
//
// Чего здесь нет и почему:
//  - поворота. Панель на этой плате уже альбомная (320x170), а поворот
//    добавляет в интерфейс состояние, которое никто не меняет;
//  - яркости. Подсветка включается и выключается: на плате стоит повышающий
//    преобразователь, и ШИМ на его разрешающем пине даёт мерцание, а не
//    градации (docs/board.md, §8);
//  - чтения из панели. Ни одна задача A1 не требует прочитать пиксель
//    обратно, а линия RD на этой плате даже не разведена как вход.

#pragma once

#include <stdbool.h>
#include <stdint.h>

// Ширина и высота панели в пикселях. Спрашивать, а не брать из board_pins.h:
// вызывающему коду незачем знать, какая именно панель стоит на плате.
int lcd_width(void);
int lcd_height(void);

// Поднять питание панели, настроить шину, сбросить панель и послать ей
// начальные команды. Заливка после этого работает; подсветка остаётся
// выключенной, её включает lcd_backlight.
//
// Возврата ошибки нет намеренно: прочитать из панели нечего, поэтому
// «инициализировалась» здесь означает только «наши записи прошли». Проверять
// приходится глазами - цветной заливкой.
void lcd_init(void);

// Подсветка: только вкл/выкл (см. выше). Включать после lcd_init: питание
// панели должно быть поднято раньше, иначе экран остаётся тёмным.
void lcd_backlight(bool on);

// Залить прямоугольник w x h в точку (x, y). Пиксели - RGB565, построчно,
// без пропусков: строка занимает ровно w * 2 байта.
//
// Функция синхронная: возвращается, когда байты ушли в панель. Асинхронная
// заливка (DMA + прерывание) появится вместе с планировщиком: сейчас
// прерывания в системе не обрабатываются вообще, и ждать их нечем.
void lcd_flush(int x, int y, int w, int h, const uint16_t *pixels);
