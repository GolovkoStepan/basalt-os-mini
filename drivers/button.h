// Кнопки платы - то немногое, что можно нажать без клавиатуры.
//
// Зачем отдельный интерфейс, а не pin_gpio_read прямо в приложении. Кнопка -
// это не «пин», а «событие»: у неё есть дребезг, полярность и назначение.
// Приложение должно спрашивать «нажата ли», а не помнить, что G0 замыкается
// на землю и что подтяжка нужна к питанию. Когда появится вторая плата с
// кнопками на другой микросхеме (или вообще без них), заменится реализация,
// а не вызывающий код.

#pragma once

#include <stdbool.h>

typedef enum {
    // G0: BOOT и одновременно Ctrl-C. Единственная кнопка, до которой можно
    // дотянуться, не глядя на плату.
    BUTTON_PRIMARY = 0,
    // G14: пока свободна. В ROADMAP - Esc, то есть переключение консолей.
    BUTTON_SECONDARY = 1,
} button_id;

// Настроить пины. Вход с подтяжкой к питанию: кнопка замыкает на землю,
// в покое линия держится в единице.
void button_init(void);

// Нажата ли кнопка прямо сейчас. Дребезг здесь не фильтруется: фильтр зависит
// от того, как часто вызывают, и живёт у вызывающего.
bool button_down(button_id id);
