// Всё, что зависит от платы LilyGO T-Display-S3 (ESP32-S3R8, 16 МБ flash,
// 8 МБ PSRAM). Магических чисел GPIO в логике быть не должно: правим только
// этот файл. Документ платы - docs/board.md.
//
// Источник: pin_config.h из официального репозитория LilyGO T-Display-S3
// (examples/factory). На своём железе ещё не сверялось - при первом включении
// проверяется экраном и замером, результаты идут в docs/board.md.

#pragma once

// --- Экран ST7789 320x170, 8-битная параллельная шина (LCD_CAM/i80) -------
// Не SPI: у этой платы экран висит на параллельной шине, где WR тактирует
// передачу, а DC выбирает «команда или данные». Отсюда восемь линий данных
// вместо одной и вдвое больше кода на инициализацию - но и вчетверо быстрее
// заливка, чем по SPI на 40 МГц.
//
// Почему 8 бит, а не 16: у ESP32-S3 i80 ограничен восемью линиями, и
// шестнадцать пинов на плате просто не разведены.
#define PIN_DISP_D0    39
#define PIN_DISP_D1    40
#define PIN_DISP_D2    41
#define PIN_DISP_D3    42
#define PIN_DISP_D4    45
#define PIN_DISP_D5    46
#define PIN_DISP_D6    47
#define PIN_DISP_D7    48

#define PIN_DISP_WR    8    // такт передачи (пиксельклок)
#define PIN_DISP_RD    9    // чтение - не используем, но пин занят панелью
#define PIN_DISP_DC    7    // 0 = команда, 1 = данные
#define PIN_DISP_CS    6
#define PIN_DISP_RST   5
#define PIN_DISP_BL    38   // подсветка, только вкл/выкл

// Раздельная линия питания панели. Поднимается до включения подсветки, иначе
// экран остаётся тёмным при полностью рабочей прошивке.
#define PIN_POWER_ON   15

// Панель физически 320x170 в альбомной ориентации - это её родной поворот,
// поэтому поворот 0 (в отличие от Cardputer, где панель портретная).
#define DISP_WIDTH  320
#define DISP_HEIGHT 170

// Частота пиксельклока из заводского примера LilyGO. Ниже - мерцание, выше -
// «мозаика» на части панелей. Замер на своём железе - в A1.
#define DISP_PIXEL_CLOCK_HZ (16 * 1000 * 1000)

// MADCTL - как панель раскладывает пиксели в своей памяти. 0x60: обмен осей
// (MV) плюс зеркало по X (MX), то есть альбомные 320x170 поверх портретной
// памяти контроллера. Без MV запись шире 240 столбцов заворачивается в
// следующую строку, и на экране получается полосатая половина картинки -
// проверено на живой плате 06.11.2026. 0x08 меняет местами красный и синий
// (BGR), 0x40 и 0x80 зеркалят оси. Значение проверяется заливкой полосами -
// docs/board.md, §10.
#define DISP_MADCTL 0x60

// Смещение видимой области внутри памяти контроллера. Стекло панели уже
// памяти: 170 столбцов при 240 у ST7789, то есть по 35 невидимых столбцов с
// каждой стороны. В альбомной ориентации (MADCTL с MV) эти столбцы становятся
// строками, поэтому смещение - по Y. Без него низ экрана остаётся с тем, что
// было в памяти до нас (проверено на живой плате 06.11.2026).
#define DISP_X_OFFSET 0
#define DISP_Y_OFFSET 35

// Инверсия цветов. Зависит от стекла, которое наклеил производитель, а не от
// контроллера: у части партий без неё красный показывается голубым, а синий -
// жёлтым. Замерено 06.11.2026 на этом экземпляре: без INVON синяя рамка вышла
// жёлтой, то есть цвет был ровно дополнением до белого. Значит стекло IPS
// требует инверсии, как и в заводском примере LilyGO.
#define DISP_INVERT_COLORS 1

// --- Кнопки ---------------------------------------------------------------
// Родных кнопок две, и обе нужны: G0 - BOOT и одновременно «Ctrl-C», G14 -
// вторая. Клавиатуры на плате нет, ввод идёт через USB Serial/JTAG.
#define PIN_BUTTON_G0  0
#define PIN_BUTTON_2   14

// --- Прочее ---------------------------------------------------------------
#define PIN_BAT_ADC    4    // делитель 2:1
// Шина I2C: на обычной плате к ней ничего не подключено (эти же пины заняты
// тач-панелью на ревизии Touch), но разъём для внешних модулей есть.
#define PIN_IIC_SCL    17
#define PIN_IIC_SDA    18

// Слот microSD на этой плате распаян, но однобитный: CMD/CLK/D0, без D1..D3.
// Драйвер - веха A3, здесь только номера пинов, чтобы не искать их заново.
#define PIN_SD_CMD     13   // он же CS в SPI-режиме
#define PIN_SD_CLK     11
#define PIN_SD_D0      12

// Индикатора жизни на этой плате нет: WS2812 отсутствует. Роль индикатора
// играет подсветка экрана - см. arch/xtensa/indicator_backlight.c.
