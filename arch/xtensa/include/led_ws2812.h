// WS2812 на G21 - единственный канал обратной связи, которому не нужен USB.
//
// Зачем отдельный драйвер: терминал на маке может быть закрыт, кабель -
// отключён, но индикатор «система жива» обязан работать. В логе этого не
// видно, светодиод видно всегда.
//
// Почему RMT, а не «дёргать пин в цикле»: WS2812 различает биты длительностью
// импульса с точностью порядка 150 нс. В цикле на C любой обработчик
// прерывания (а FreeRTOS в этой сборке тикает) сдвигает фронт, и в лучшем
// случае цвет врёт, в худшем - весь кадр уходит в мусор. RMT вычитывает
// последовательность из памяти канала сам, независимо от загрузки процессора.

#pragma once

#include <stdbool.h>
#include <stdint.h>

// Поднимает питание светодиода, тактирование RMT и маршрут сигнала на пин.
// Требует инициализированного тика: задержки между кадрами считаются по нему.
void basalt_led_init(void);

// Установить цвет. Значения 0..255, яркость не масштабируется - пусть её
// выбирает вызывающий: индикатор «работает» не должен слепить в темноте.
void basalt_led_set(uint8_t r, uint8_t g, uint8_t b);

// Доступна ли память канала на запись. false означает, что кадры уходят в
// никуда - стоит печатать это в лог при старте, иначе отказ молчаливый.
bool basalt_led_memory_ok(void);

// Готов ли драйвер к работе. До инициализации панике нельзя трогать RMT:
// блок ещё не тактируется, и запись в его регистры ничего не даст.
bool basalt_led_ready(void);

// Сколько микросекунд занял последний кадр. 24 бита по 1.2 мкс - это ~29 мкс;
// заметно меньшее значение означает, что частота передачи неверна, и лента
// такой кадр не примет.
uint32_t basalt_led_frame_us(void);
