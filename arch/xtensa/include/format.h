// Вывод чисел в консоль без printf.
//
// Зачем свой: printf тянет newlib и таблицу форматов, а нам нужны три
// операции - строка, десятичное число и hex. В панике это ещё и вопрос
// надёжности: чем меньше кода участвует в выводе, тем меньше способов
// не напечатать ничего.
//
// Модуль намеренно не знает, куда пишет: он складывает байты в консоль
// (arch/xtensa/console_usb_jtag.c). Когда появится экран, его можно будет
// добавить здесь же, не трогая вызывающих.

#pragma once

#include <stddef.h>
#include <stdint.h>

// Строка целиком. Ноль-терминатор обязателен.
void basalt_put(const char* s);

// Десятичное число без ведущих нулей.
void basalt_put_u64(uint64_t v);

// То же число, но в буфер, а не в консоль: возвращает указатель на первый
// символ внутри buf. Нужно там, где писать надо не в консоль (экран), а
// формат должен остаться один - иначе число на экране и в логе однажды
// разойдётся. cap - размер buf, меньше 21 не бывает смысла.
const char* basalt_format_u64(char* buf, size_t cap, uint64_t v);

// Hex с фиксированным числом знаков: 8 - полное слово, 2 - байт.
void basalt_put_hex(uint32_t v, int digits);

// Доля part от total в процентах, целым числом, с округлением к ближайшему.
// Зачем отдельной функцией: процентов теперь два места (стек в `top`, куча в
// `free`), и две копии формулы разошлись бы на первом же округлении - «12%» в
// одном отчёте и «11%» в другом про одно и то же число.
//
// part не больше total (доля, а не отношение). При total == 0 пишется «0»:
// делить не на что, и врать про процент пустой области незачем.
const char* basalt_format_percent(char* buf, size_t cap, uint64_t part, uint64_t total);

// Секунды с тремя знаками после точки: «1.234». Отдельный формат нужен,
// чтобы подъём счётчика был виден глазом, а не сливался в одно число.
void basalt_put_sec3(uint64_t us);
