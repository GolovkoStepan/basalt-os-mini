// Вывод чисел в консоль без printf.
//
// Зачем свой: printf тянет newlib и таблицу форматов, а нам нужны три
// операции - строка, десятичное число и hex. В панике это ещё и вопрос
// надёжности: чем меньше кода участвует в выводе, тем меньше способов
// не напечатать ничего.
//
// Модуль намеренно не знает, куда пишет: он складывает байты в консоль
// (arch/xtensa/console_usb_jtag.c). Когда появится экран, его можно будет
// добавить здесь же, не трогая вызывающих.

#pragma once

#include <stdint.h>

// Строка целиком. Ноль-терминатор обязателен.
void basalt_put(const char* s);

// Десятичное число без ведущих нулей.
void basalt_put_u64(uint64_t v);

// Hex с фиксированным числом знаков: 8 - полное слово, 2 - байт.
void basalt_put_hex(uint32_t v, int digits);

// Секунды с тремя знаками после точки: «1.234». Отдельный формат нужен,
// чтобы подъём счётчика был виден глазом, а не сливался в одно число.
void basalt_put_sec3(uint64_t us);
