// Индикатор «система жива» - единственный канал обратной связи, которому не
// нужен USB.
//
// Зачем отдельный интерфейс: терминал на маке может быть закрыт, кабель -
// отключён, но признак жизни обязан быть виден глазом. В логе этого не видно,
// индикатор видно всегда.
//
// Почему интерфейс, а не драйвер: у плат он разный. На Cardputer это WS2812 на
// G21 через RMT, на T-Display-S3 - подсветка экрана. Реализация выбирается
// сборкой (src/CMakeLists.txt), поэтому #ifdef по платам в коде нет: каждая
// плата приносит свой файл с этими же символами.
//
// Имена basalt_indicator_*, а не led_*: светодиод есть только на одной из плат,
// а интерфейс общий. Вызывающий код спрашивает «дай признак жизни», а не
// «зажги такой-то диод».

#pragma once

#include <stdbool.h>
#include <stdint.h>

// Человеческое описание того, чем эта сборка сигналит. Нужно логу при старте:
// «индикатор есть» и «индикатор - вот такой» - разные утверждения, и при
// отладке платы первое без второго бесполезно.
const char* basalt_indicator_name(void);

// Поднять питание и маршрут сигнала индикатора.
// Требует инициализированного тика: паузы между кадрами считаются по нему.
void basalt_indicator_init(void);

// Включить индикатор. Значения 0..255, яркость не масштабируется - пусть её
// выбирает вызывающий: индикатор «работает» не должен слепить в темноте.
// Для плат с одноцветным индикатором (подсветка) важно только «есть ли цвет»:
// (0,0,0) - погасить, любое другое - включить.
void basalt_indicator_set(uint8_t r, uint8_t g, uint8_t b);

// Доступна ли память передатчика на запись. false означает, что кадры уходят
// в никуда - стоит печатать это в лог при старте, иначе отказ молчаливый.
// У плат без передатчика (подсветка) всегда true: проверять нечего.
bool basalt_indicator_memory_ok(void);

// Готов ли индикатор к работе. До инициализации панике нельзя трогать
// периферию: она ещё не тактируется, и запись в регистры ничего не даст.
bool basalt_indicator_ready(void);

// Сколько микросекунд занял последний кадр. У WS2812 24 бита по 1.2 мкс - это
// ~29 мкс; заметно меньшее значение означает, что частота передачи неверна, и
// лента такой кадр не примет. У подсветки кадра нет - возвращается 0.
uint32_t basalt_indicator_frame_us(void);
