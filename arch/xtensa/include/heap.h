// do_core_init() - перечень ESP_SYSTEM_INIT_FN, а его вызывает
// start_cpu0_default, которую мы перекрыли своим start_cpu0 (см. start.h).
// Значит кучу обязана завести платформа, и место этому - arch/: на P4 будет
// другой arch с другой кучей, а код выше arch/ не должен об этом знать.
//
// Почему в start_cpu0, а не первой строкой basalt_main: приложение не должно
// помнить, что перед первым heap_caps_* нужно что-то вызвать. Забыть легко,
// а проявится это не ошибкой компиляции, а NULL из malloc - далеко от причины.
// Цена решения: если куча не завелась, сказать об этом некуда, консоли в этот
// момент ещё нет. Проверять надо снаружи, щупом env:probe.

