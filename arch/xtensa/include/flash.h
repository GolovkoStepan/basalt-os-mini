// Встроенный flash: чтение, стирание сектора, запись.
//
// Зачем свой модуль, если в IDF есть esp_flash. Драйвер flash заводит
// do_core_init() (ESP_SYSTEM_INIT_FN с приоритетом 130), а мы перекрыли
// start_cpu0 и do_core_init не зовём. Поэтому esp_flash_default_chip == NULL,
// esp_flash_get_size(NULL) возвращает ошибку, а esp_flash_read без аргумента
// падает. Завести драйвер обязана платформа, и место этому - arch/.
//
// Зачем свой интерфейс поверх чужого драйвера, а не только чужая функция.
// Наружу нужны пять операций и размер; всё остальное (chip driver, режим
// чтения, стирание блоками, работа с регистрами) - подробность реализации.
// Когда в A9 появится своя таблица разделов и своя ФС, менять придётся этот
// файл, а не вызывающих.
//
// Что взято готовым и почему. Инициализация чипа - esp_flash_init_default_chip
// в режиме no-OS (esp_flash_noos_functions): он гасит кэш на время операции и
// не требует ни FreeRTOS, ни замков, ни очередей, ни таблицы разделов - то
// есть ровно то, что нужно системе без планировщика. Цена честная и её надо
// помнить: пока кэш выключен, PSRAM недоступна, поэтому буфер любой операции
// обязан лежать в SRAM. Писать свой SPI-драйвер NOR-flash (статусные
// регистры, WEL, режимы 24/32 бита, ожидание готовности) - вечер на пустом
// месте: у IDF этот код уже проверен на всех чипах.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Размер стираемого сектора. 4 КБ у всех NOR-flash, которые ставят на эти
// платы, но цифру всё равно печатает щуп env:flash: стирать не тем блоком -
// это испорченные соседние данные, и узнаётся об этом позже.
#define BASALT_FLASH_SECTOR_SIZE 4096u

// Завести драйвер. Возвращает 0 или код ошибки esp_err_t как есть (своих кодов
// пока нечего различать). Повторный вызов ничего не делает.
//
// Вызывает приложение, а не start_cpu0: пока драйвер нужен одному щупу, в
// проверенных сборках A0 ему делать нечего. Когда ФС понадобится всем (A9),
// вызов переедет в basalt_start_c - рядом с basalt_heap_init.
int basalt_flash_init(void);

// Готов ли драйвер (был ли успешный basalt_flash_init).
bool basalt_flash_ready(void);

// Размер, который разрешено использовать, байт. Его сообщает загрузчик, и на
// этой плате он совпадает с физическим (проверено env:flash 06.11.2026).
// Отдельная функция всё равно нужна: если однажды объявленный окажется меньше,
// драйвер откажется работать за его границей, и разница должна быть видна, а не
// выясняться записью в несуществующий адрес.
uint32_t basalt_flash_size(void);

// Физический размер чипа, байт. Не зависит от того, что объявлено в образе.
uint32_t basalt_flash_physical_size(void);

// JEDEC ID: производитель, тип, объём одним словом.
uint32_t basalt_flash_id(void);

// Ошибки - те же коды esp_err_t, что вернул драйвер; 0 - успех.
int basalt_flash_read(uint32_t address, void* dst, size_t length);

// Стереть сектор размером BASALT_FLASH_SECTOR_SIZE. Адрес обязан быть
// выровнен по границе сектора.
int basalt_flash_erase_sector(uint32_t address);

// Записать length байт в стёртую область. Стирание не делает: NOR-flash умеет
// только менять 1 на 0, и запись поверх нестёртого даёт мусор, а не ошибку.
int basalt_flash_write(uint32_t address, const void* src, size_t length);
