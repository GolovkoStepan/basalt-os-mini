// Консоль поверх USB Serial/JTAG - своего драйвера, без Arduino HWCDC и без
// IDF usb_serial_jtag_ll.
//
// Почему свой драйвер, а не готовый: USB Serial/JTAG - единственный путь
// вывода, который у нас есть на этой плате (моста UART->USB нет). Всё, что
// печатает ядро, паника и шелл, пойдёт через него. Взять готовый - значит
// тащить за собой инициализацию, прерывания и очередь FreeRTOS, то есть
// ровно то, от чего A0 уходит.
//
// Периферия простая: FIFO на 64 байта в каждую сторону, два флага в EP1_CONF.
// Байт пишется в EP1_REG, читается оттуда же. Прерывания не нужны - опрос.

#pragma once

#include <stddef.h>
#include <stdint.h>

void basalt_console_init(void);

// Пишет ровно len байт. Возвращает сколько удалось: если хост не забирает
// данные (терминал не открыт), запись обрывается по счётчику, а не висит.
size_t basalt_console_write(const void* data, size_t len);

// Читает до len байт из FIFO. Возвращает 0, если данных нет.
size_t basalt_console_read(void* data, size_t len);
