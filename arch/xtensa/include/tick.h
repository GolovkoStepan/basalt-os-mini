// Тик и монотонное время - из системного таймера напрямую по регистрам.
//
// SYSTIMER - это два независимых 64-битных счётчика, тактируемых от 16 МГц.
// Берём Unit 0 как есть: он же используется IDF для esp_timer, но нам нужен не
// чужой API, а счётчик, поэтому читаем значение сами.
//
// Почему не CCOMPARE: CCOMPARE даёт прерывание, а прерываний на A0 нет.
// Счётчик + сравнение в цикле достаточно для uptime и не требует векторов.

#pragma once

#include <stdint.h>

// Частота счётчика Unit 0. Не константа платы, а параметр SoC.
#define BASALT_TICK_HZ 16000000u

void basalt_tick_init(void);

// Значение счётчика. Читается через регистр UPDATE: без него в VALUE лежит
// снимок, сделанный в момент предыдущего обновления.
uint64_t basalt_tick_cycles(void);

// Микросекунды с запуска счётчика.
uint64_t basalt_uptime_us(void);

// Ожидание опросом. Пока нет планировщика, другого способа подождать нет.
void basalt_delay_us(uint32_t us);
