// Задачи: свой стек на задачу и переключение контекста.
//
// ЗАЧЕМ ЭТОТ МОДУЛЬ.
//
// До него система была одним потоком: всё работало в цикле basalt_main, и
// «параллельность» означала «сначала одно, потом другое». Задача нужна, чтобы
// две вещи могли идти одновременно - например, шелл ждёт ввода, а часы тикают.
//
// ПОЧЕМУ КООПЕРАТИВНО, А НЕ ВЫТЕСНЯЮЩЕ.
//
// Вытеснение на Xtensa стоит дорого не по тактам, а по цене ошибки. Чтобы
// переключить задачу из обработчика тика, надо одновременно: сбросить окна
// регистров на стек задачи, снять PS.EXCM (иначе `entry` в любой функции даст
// двойное исключение), положить кадр не поверх стека прерванного кода (иначе
// затрётся спилл окон [sp-12] - эта ошибка уже была поймана на шаге 1), и
// вернуться через `rfi 3` с чужим PS. Ошибка в любом из этих мест выглядит не
// как «не собралось», а как молчащая плата.
//
// Кооперативный вариант убирает из этого списка вход через вектор и EXCM:
// переключение происходит в обычном коде, по явному basalt_task_yield(). Зато
// остаётся ровно то, что нам нужно проверить на живой плате, - механизм окон.
// Когда он проверен, вытеснение по тику становится обвязкой вокруг того же
// basalt_task_switch(), а не отладкой всего сразу.
//
// ПОЧЕМУ РЕГИСТРЫ НЕ НА СТЕКЕ «СВЕРХУ».
//
// Соблазн: при переключении положить a0..a15 на стек текущей задачи и потом
// снять. Так делать нельзя, и это не осторожность, а требование ABI. Область
// [sp-16 .. sp-4] занята спиллом окон: туда аппаратура кладёт регистры предка
// при переполнении окна, и обработчик переполнения читает оттуда (через
// [a1-12]) указатель кадра предка. Запись в эту область портит цепочку кадров,
// и следующий же вызов функции в задаче уходит в обработчик с мусором вместо
// указателя. Проверено на плате в шаге 1: падение в одном прогоне из трёх,
// то есть выглядело как случайность.
//
// Поэтому порядок обратный: сначала SPILL_ALL_WINDOWS сбрасывает живые окна
// каждой задачи в её собственные кадры на её же стеке, и только потом
// сохраняется контекст. И его хватает всего два числа: указатель стека и PS.
// Адрес возврата и регистры предков уже лежат в кадрах на стеке задачи, а
// `retw` вернёт вызывающему его a1 сам - поэтому 64 регистра не нужны.
//
// И ещё одна вещь, которую трогать НЕ надо: WINDOWSTART. Маска живых окон -
// не состояние задачи: `retw` и обработчики недобора восстанавливают регистры
// из кадров на стеке, и подсунутая готовая маска обходит этот механизм.
// Проверено на плате: плата замолкала ровно при возврате в задачу.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Размер стека задачи. 4 КБ - не экономия: шелл с редактором строки занимает
// под 2 КБ в самом глубоком месте (замерено `top`), а задача с печатью через
// матрицу добавит ещё. Стек выделяется из внутренней памяти, не из PSRAM:
// PSRAM идёт через кэш, а кэш драйвер flash гасит на время записи.
#define BASALT_TASK_STACK_SIZE 4096u

// Сколько задач максимум. Четыре слота при стеке 4 КБ - это 16 КБ внутренней
// памяти, а она у нас не бесконечна (см. `top`).
#define BASALT_TASK_MAX 4u

typedef void (*basalt_task_fn)(void* arg);

// Описание задачи для создания. Отдельная структура, а не пять аргументов:
// поле проще добавить, не переписывая все вызовы, и в отчёте `top` видно, что
// у задачи есть имя.
typedef struct {
    const char* name;   // имя для `top`; строка должна жить, пока живёт задача
    basalt_task_fn fn;  // что делать; возврат из функции завершает задачу
    void* arg;          // аргумент функции
    size_t stack_size;  // 0 - BASALT_TASK_STACK_SIZE
} basalt_task_config_t;

typedef enum {
    BASALT_TASK_FREE = 0,  // слот пуст
    BASALT_TASK_READY,     // готова выполняться
    BASALT_TASK_RUNNING,   // выполняется прямо сейчас
    BASALT_TASK_BLOCKED,   // спит до срока, с выбора снята
    BASALT_TASK_DONE,      // функция вернулась, стек можно освобождать
} basalt_task_state_t;

// Сведения о задаче для отчёта. Указатели наружу не отдаём: `top` печатает
// только числа, а структура задачи - внутреннее дело модуля.
typedef struct {
    const char* name;
    basalt_task_state_t state;
    size_t stack_used;  // байт от дна до текущей вершины (watermark)
    size_t stack_size;
    uint32_t switches;  // сколько раз задачу выбирали на выполнение
    uint8_t cpu_percent;  // доля процессора за последний интервал, 0..100
    uint32_t wake_in_ms;  // спящая: сколько ещё ждать; иначе 0
} basalt_task_info_t;

// Завести планировщик. Вызывается один раз при старте, до создания задач.
// Текущий поток становится задачей 0 с именем `name`: у него уже есть стек,
// и переезжать ему никуда не нужно.
//
// Почему текущий поток - задача, а не «вне планировщика»: иначе у
// переключения было бы два разных случая (в задачу и обратно из ниоткуда), а
// это вдвое больше кода, который может быть неверным.
void basalt_task_init(const char* name);

// Создать задачу. Возвращает false, если слотов нет или память не выделилась.
bool basalt_task_create(const basalt_task_config_t* cfg);

// Отдать процессор следующей готовой задаче. Возвращается, когда очередь
// снова дойдёт до вызывающего.
//
// Возвращает true, если переключение состоялось. Это нужно главному циклу:
// если процессор кому-то отдали, спать сразу нельзя - иначе отданная задача
// получит управление только через тик.
//
// Это единственная точка, где происходит переключение. Она вызывается из
// обычного кода, поэтому здесь нет ни EXCM, ни кадра прерывания - только окна.
bool basalt_task_yield(void);

// Спать `ms` миллисекунд. Задача снимается с выбора и не мешает остальным:
// это главное отличие от basalt_idle_ms, который останавливает всю систему.
//
// 0 означает «до следующего тика»: так задача уступает процессор, не назначая
// срока, - полезно в опросе без таймера.
//
// Внутри - yield до тех пор, пока срок не наступит. Спит не ядро, а задача:
// остальные в это время работают.
void basalt_task_sleep_ms(uint32_t ms);

// Подождать, когда работы нет: разбудить просроченные задачи и уснуть до
// ближайшего прерывания.
//
// Зачем отдельная функция, если есть basalt_idle_wait: перед сном нужно
// разбудить тех, чей срок наступил. Без этого задача, чей срок прошёл, пока
// система была занята, простояла бы лишний тик. Главному циклу и сну задачи
// нужен один и тот же порядок «сначала проверить время, потом спать», и
// дублировать его в двух местах - верный способ разойтись.
void basalt_task_wait(void);

// Завершить текущую задачу. Не возвращается.
void basalt_task_exit(void) __attribute__((noreturn));

// Сколько всего было переключений. Для `top` и для проверки на плате: ноль
// означал бы, что yield не работает, а не что «переключаться не на кого».
uint32_t basalt_task_switches(void);

// Сколько задач заведено (включая завершённые, но ещё не собранные).
size_t basalt_task_count(void);

// Сведения о задаче по индексу. false - индекс вне диапазона.
bool basalt_task_get(size_t index, basalt_task_info_t* out);

// Номер выполняющейся задачи.
size_t basalt_task_current(void);

// Разбудить задачи, чей срок наступил. Зовут из basalt_task_yield и
// basalt_task_wait: планировщик сам не просыпается, его будит время.
//
// Почему не из обработчика тика: обработчик не пишет на стек прерванного кода
// и не зовёт функций C, а разбор таблицы задач - именно функция C. Пока сон
// проверяется в обычном коде, этого достаточно: тик и так будит систему сто
// раз в секунду.
size_t basalt_task_wake_due(void);

// Ближайший срок пробуждения в микросекундах uptime. 0 - спящих нет.
//
// Пока никем не зовётся: `waiti` будится тиком, и тик идёт чаще любого срока.
// Оставлено, потому что понадобится, когда появится сон без тика (гашение
// тактирования и пробуждение от SYSTIMER) - там решение «до чего спать»
// станет обязательным.
uint64_t basalt_task_next_wake(void);

// Сколько готовых задач (READY + RUNNING). Ноль значит, что все спят.
size_t basalt_task_ready_count(void);

// Учёт процессорного времени: начинает новый интервал замера.
//
// Зовётся из главного цикла раз в полсекунды. Считается по времени, а не по
// числу переключений: переключения говорят, как часто задачу выбирали, но не
// сколько она работала - главная за одну итерацию читает USB и рисует экран, а
// фоновая делает одну операцию.
void basalt_task_cpu_sample(void);

// Доля времени, которое система проспала в waiti за последний интервал.
//
// Нужна, чтобы сумма «задачи + сон» сходилась к 100: без неё занятость задач
// выглядела бы выше, чем есть, и непонятно было бы, куда делся остаток.
uint8_t basalt_task_idle_percent(void);
