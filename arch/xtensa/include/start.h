// Своя точка входа в приложение.
//
// Где мы находимся в цепочке старта. Загрузчик (второй ступени, чужой) грузит
// образ в память и прыгает на `call_start_cpu0` в порту IDF. Тот делает то,
// что без него не сделать: настраивает кэш и MMU, поднимает частоту, стирает
// BSS, ставит VECBASE на таблицу векторов. Затем вызывает `start_cpu0`.
//
// `start_cpu0` в IDF объявлен weak - это штатная точка расширения. Мы её
// перекрываем своей, и с этого момента управление больше не возвращается в
// IDF: планировщик FreeRTOS не запускается, `main_task` не создаётся,
// `app_main` не вызывается. Наша система - это цикл в `basalt_main`.
//
// Что мы сознательно оставляем чужому: `call_start_cpu0`. Написать вместо
// него свой - значит переписать настройку кэша, MMU и тактирования, а ошибка
// там даёт молчащую плату. Это работа не для A0.

#pragma once

// Точка входа в нашу систему. Вызывается из basalt_start на своём стеке.
// Не возвращается никогда.
void basalt_main(void) __attribute__((noreturn));

