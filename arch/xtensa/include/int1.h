// Таймерное прерывание для будущего планировщика: тики по CCOMPARE1.
//
// Зачем отдельный слой, если уже есть uptime. Uptime отвечает на вопрос
// «сколько прошло», но не умеет ничего делать сам: пока его опрашивают, ядро
// занято циклом. Первое прерывание нужно затем, чтобы система могла узнать о
// ходе времени без опроса - это основа шага 2 вехи A6 (переключение контекста
// по тику) и любого сна, который не сжигает процессор.
//
// ПОЧЕМУ УРОВЕНЬ 3, А НЕ УРОВЕНЬ 1.
//
// Первый вариант был на CCOMPARE0 - линия 6, уровень 1. Он не годится по цене
// ошибки: у уровня 1 на XEA2 нет регистра EPS_1, поэтому PS приходится
// сохранять вручную, а его слот делится с исключениями ядра (0x300) и
// пользователя (0x340) - прерывание приходит в один из двух в зависимости от
// режима прерванного кода, и это надо разбирать по EXCCAUSE. Проверено на
// плате: ошибка в таком обработчике не даёт отчёта вообще - плата замолкает до
// ручного сброса.
//
// CCOMPARE1 - линия 15, уровень 3. Аппаратура сама кладёт старое PS в EPS_3 и
// PC в EPC_3, возврат делает одна инструкция `rfi 3`, и у уровня свой слот
// 0x1C0. Тик от этого не хуже, а цена ошибки на порядок ниже.
//
// Цена выбора: CCOUNT считает такты ядра, поэтому период зависит от частоты.
// Частота берётся из sdkconfig, а не предполагается: на 80 МГц тот же период
// означал бы вдвое медленный тик. Uptime по-прежнему считается по SYSTIMER
// (16 МГц), который от частоты ядра не зависит.

#pragma once

#include <stdint.h>

// Частота тика. 100 Гц - 10 мс: достаточно мелко для планировщика и при этом
// накладные расходы незаметны (около тридцати инструкций на тик).
#define BASALT_INT1_HZ 100u

// Запустить таймер и разрешить прерывание уровня 1.
// Вызывается один раз при старте, после установки таблицы векторов: до этого
// прерывание пришло бы в чужую таблицу.
void basalt_int1_init(void);

// Сколько тиков прошло. Читается без остановки прерываний: 32-битное чтение
// на Xtensa атомарно, а переполнение счётчика наступит через 497 дней работы.
uint32_t basalt_int1_ticks(void);

// Период в тактах ядра - для отчёта и проверки глазами.
uint32_t basalt_int1_period(void);

// Частота ядра, на которую настроен период. Вынесена в интерфейс, потому что
// именно её сверяют с секундомером при проверке на плате.
uint32_t basalt_int1_cpu_hz(void);

// Состояние, по которому видно, почему прерывание не приходит: разрешена ли
// линия и какой уровень замаскирован. Нужна для разбора на плате, потому что
// «тики не растут» одинаково выглядит при трёх разных причинах: бит не
// выставлен в INTENABLE, порог в PS слишком высок, или CCOMPARE0 стоит в
// прошлом и линия уже поднята, но не обслуживается.
typedef struct {
    uint32_t intenable;   // маска разрешённых линий
    uint32_t interrupt;   // линии, которые просят обслуживания прямо сейчас
    uint32_t ps;          // текущий PS: младшие 4 бита - INTLEVEL
    uint32_t ccount;      // счётчик тактов
    uint32_t ccompare;    // порог CCOMPARE0
} basalt_int1_state_view_t;

void basalt_int1_view(basalt_int1_state_view_t* out);

// Погасить и вернуть таймерную линию. Нужна на время работы с flash.
//
// Зачем. Драйвер flash в режиме no-OS гасит кэш на время стирания и записи - десятки
// миллисекунд. Обработчик тика лежит в IRAM и переживёт это, но с шага 5 он
// зовёт функцию C выбора задачи, а та живёт во flash: вызов при погашенном кэше
// уронил бы систему. В IRAM переезжать всей веткой выбора задачи - это тащить
// туда таблицу задач и весь ABI вызова, поэтому дешевле не пускать тик.
//
// Пара, а не «запретить навсегда»: операции с flash бывают вложенными (ФС
// стирает перед записью), и линия должна включиться ровно после внешней.
// Счётчик вложенности, потому что снимать маску раньше внешней операции нельзя.
void basalt_int1_hold(void);
void basalt_int1_release(void);
