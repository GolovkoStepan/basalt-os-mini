// Свой обработчик исключений - «паника».
//
// Зачем свой, если у IDF он есть: чужой печатает свои поля своим форматом и
// решает за нас, что важно. Нам нужно три вещи, которых он не даёт:
//
//  1. Понятный человеку текст: не «EXCCAUSE: 0x00000006», а «деление на ноль»,
//     и рядом объяснение, что такое EPC1 и EXCVADDR.
//  2. Светодиод красным до сброса. Лог может не дойти до хоста - кабель
//     отключён, терминал закрыт, - а цвет видно всегда.
//  3. Независимость от чужого кода в самом обработчике: файл не вызывает ни
//     одной функции IDF, только регистры и свои драйверы.
//
// Вызывается из своего слота таблицы векторов (vectors.S) с указателем на
// свой кадр. Из паники не возвращаются: обработчик печатает, держит паузу и
// сбрасывает чип.
//
// Чего здесь пока нет: разбора стека и имён функций. Для этого нужна
// отладочная информация и чтение стека по кадрам - отдельная работа.

#pragma once

#include <stdint.h>

// Кадр, который заполняет слот вектора. Раскладка задана в двух местах -
// здесь и в vectors.S - поэтому совпадение смещений проверяется статически
// при сборке. Поля идут подряд, без дыр.
typedef struct {
    uint32_t a0, a1, a2, a3, a4, a5, a6, a7;
    uint32_t a8, a9, a10, a11, a12, a13, a14, a15;
    uint32_t ps;
    uint32_t pc;
    uint32_t exccause;
    uint32_t excvaddr;
    uint32_t sar;
    uint32_t vector;    // номер слота: какой вектор сработал
} basalt_frame_t;

// Печатает состояние сбоя и перезагружает плату. Не возвращается.
void basalt_panic_exc(basalt_frame_t* frame) __attribute__((noreturn));

// Первая строка отчёта о сбое. Вызывается из тела слота таблицы векторов
// до передачи управления панике: если сбой случится в самом разборе, эта
// строка уже будет в консоли. Печатает только первые несколько сбоев -
// иначе цикл двойных исключений забивает лог.
void basalt_vec_note(basalt_frame_t* frame);
