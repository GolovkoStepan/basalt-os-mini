// Ожидание до прерывания: ядро спит, пока тик не разбудит.
//
// Зачем отдельный модуль, если есть basalt_delay_us. delay_us - это опрос:
// оно честно ждёт нужное время, но всё это время ядро крутится на счётчике.
// Для паузы в 500 мкс в главном цикле это нормально, а для `sleep 10` - нет:
// десять секунд полной нагрузки процессора без единой полезной работы.
//
// `waiti` останавливает ядро до ближайшего прерывания. Просыпаясь, ядро
// продолжает с той же инструкции, поэтому цикл «уснуть - проверить условие -
// уснуть» и есть весь механизм.
//
// ПОЧЕМУ ЭТО НЕ ПЛАНИРОВЩИК. Здесь ничего не переключается: спит тот же
// поток, что и вошёл. Сон задачи (сняться с выбора, отдать процессор другой) -
// это basalt_task_sleep_ms из tasks.h; он и зовёт basalt_idle_wait, когда
// готовых задач не осталось.

#pragma once

#include <stdint.h>

// Разрешить сон. Зовётся после basalt_int1_init: до этого прерывания нет, и
// waiti уснул бы навсегда - разбудить было бы некому.
void basalt_idle_init(void);

// Сколько раз ядро засыпало. Нужен, чтобы отличить «цикл спит» от «цикл
// крутится»: при простое число растёт примерно на 100 в секунду (по тику), и
// если оно больше - значит, работу будят другие прерывания, и стоит искать
// какие. Без этого «сон включён» было бы утверждением о коде, а не о плате.
uint32_t basalt_idle_waits(void);

// Спать до ближайшего прерывания. Возвращается после любого прерывания, а не
// только тика: это нормально, вызывающий перепроверяет своё условие в цикле.
void basalt_idle_wait(void);

// Ожидание не короче срока. Спит, пока время не выйдет, но не дольше
// BASALT_IDLE_MAX_SLICE_US за один waiti.
//
// Почему не «спать ровно until»: waiti просыпается на любом прерывании, и
// если бы мы проверили время только раз, любое чужое прерывание (USB,
// кнопка) возвращало бы управление раньше срока. Цикл с перепроверкой - это
// и есть правильная форма.
void basalt_idle_until_us(uint64_t until_us);

// Ожидание длительностью в миллисекундах. Отдельная обёртка, чтобы `sleep` не
// складывал микросекунды в 64-битном выражении у себя.
void basalt_idle_ms(uint32_t ms);
