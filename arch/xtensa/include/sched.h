// Выбор задачи и пробуждение по сроку - чистая логика, без регистров.
//
// ПОЧЕМУ ОТДЕЛЬНЫЙ ФАЙЛ, А НЕ ВНУТРИ tasks.c.
//
// В tasks.c рядом живут выделение стеков, снимок PS и вызов ассемблера. Такой
// файл на маке не соберётся, а именно здесь ошибки тихие: круг по задачам легко
// написать так, что задача выберется дважды подряд или не выберется никогда, и
// на плате это выглядит не как «не собралось», а как «одна из задач замерла».
// Поэтому обход круга и поиск ближайшего срока вынесены сюда, где их можно
// прогнать на хосте (test/test_sched).
//
// ВАЖНОЕ РАЗЛИЧЕНИЕ: сон задачи - не то же, что сон системы.
//
// Спящая задача снята с выбора, но остальные продолжают работать: шелл может
// спать `sleep 5`, а фоновая задача в это время тикает. Сон системы - это когда
// готовых нет вообще; тогда ядро уходит в `waiti` до ближайшего срока. Второе
// без первого бессмысленно: пока хоть одна задача готова, спать нельзя.

#pragma once

#include <stddef.h>
#include <stdint.h>

#include "tasks.h"

// Следующая готовая задача после `from`, по кругу.
//
// Возвращает индекс или (size_t)-1, если готовых нет. Готовой считается
// BASALT_TASK_READY и BASALT_TASK_RUNNING: выполняющаяся задача тоже участвует
// в круге, иначе в системе из двух задач вторая получала бы процессор только
// после того, как первая завершится.
//
// `from` может быть вне диапазона: это не ошибка, обход всё равно начнётся с
// (from + 1) % n - так вызывающему не нужно проверять границу.
size_t sched_pick(const basalt_task_state_t* states, size_t n, size_t from);

// Ближайший срок пробуждения среди спящих. 0 - спящих нет.
//
// Пока не зовётся: `waiti` возвращается на тике, а тик идёт 100 раз в секунду,
// поэтому спать «ровно до срока» дольше тика всё равно не выйдет. Пригодится,
// когда тик перестанет быть единственным источником пробуждения.
uint64_t sched_next_wake(const basalt_task_state_t* states, const uint64_t* wake_at, size_t n);
// Разбудить все задачи, чей срок наступил. Возвращает, сколько разбудил.
//
// Срок `<= now` считается наступившим. Строгое `<` теряло бы задачу, которая
// проснулась ровно в свой срок: теперь - это то же самое «пора», а не «ещё
// рано», и задача ждала бы следующего тика без причины.
size_t sched_wake_due(basalt_task_state_t* states, const uint64_t* wake_at, size_t n, uint64_t now);
