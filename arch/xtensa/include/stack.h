// Стек: сколько его уже израсходовано.
//
// Зачем это вообще. Стек у нас один и свой (8 КБ, start.S), и «сколько
// осталось» - главный вопрос при любом непонятном падении: переполнение стека
// на xtensa не даёт внятной ошибки, оно молча затирает чужие данные, и
// symptoms расходятся с причиной на пол-проекта. Команда top отвечает на этот
// вопрос числом, а не догадкой.
//
// Как меряется. При старте весь стек закрашивается байтом-меткой, и потом
// граница находится по первому незакрашенному байту снизу. Это даёт максимум
// за всё время работы (watermark), а не текущую глубину: текущая глубина в
// цикле событий почти постоянна и ничего не говорит о том, насколько близко
// подошёл самый глубокий вызов - разбор команды, печать паники.
//
// Почему в arch/. Стек - свойство платформы: на P4 будет другой стек, другая
// раскладка и, возможно, сторожевой таймер вместо закраски. Код выше arch/ не
// должен знать ни про закраску, ни про то, где кончается стек.

#pragma once

#include <stddef.h>

// Закрасить свободную часть стека. Вызывается один раз при старте, на своём
// стеке и до всего остального: всё, что успеет поработать до закраски,
// закраску не испортит, но и в отчёт не попадёт.
void basalt_stack_paint(void);

// Сколько байт стека было занято в самый глубокий момент. Если закраска не
// проводилась, вернёт 0 - и это единственный способ отличить «не мерили» от
// «ничего не занято».
size_t basalt_stack_used(void);

// Полный размер стека в байтах. Нужен, чтобы показать остаток.
size_t basalt_stack_size(void);
