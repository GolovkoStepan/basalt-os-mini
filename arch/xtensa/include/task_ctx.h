// Раскладки кадров задачи, общие для двух ассемблерных файлов.
//
// ЗАЧЕМ ОБЩИЙ ФАЙЛ. Кадр пишет один файл, а читает другой: кооперативный кадр
// создаёт tasks.S, а возобновить задачу после вытеснения приходится из
// vectors.S. Разъедутся смещения - ошибка будет выглядеть не как «не собралось»,
// а как «задача продолжила с мусором в регистрах». Общий заголовок -
// единственное место, где каждое число написано один раз.
//
// Совпадение с C проверяется _Static_assert в arch/xtensa/tasks.c.

#pragma once

// --- контекст задачи (switch_ctx_t в tasks.c) -----------------------------
//
// Не «все регистры», а то, из чего задачу можно возобновить: подготовленный
// стек, PS, адреса функции и переходника, и способ, которым задача была
// остановлена. Всё остальное лежит в её кадрах на её стеке.
#define CTX_SP       0
#define CTX_PS       4
#define CTX_START    8    // 1 - задача ещё не входила ни разу
#define CTX_FN       12
#define CTX_ARG      16
#define CTX_ENTRY    20
#define CTX_PREEMPT  24   // 1 - остановлена тиком, возврат через `rfi 3`

// --- кадр тика ------------------------------------------------------------
//
// Своего кадра, а не XtExcFrame из IDF: он вдвое меньше (112 байт против 192),
// и формат никто, кроме нас, не читает - кадр прерывания из паники не
// восстанавливают. В IDF-шном есть место под exccause, excvaddr и 36 байт
// состояния сопроцессоров, которых у нас нет.
//
// Верхние 16 байт кадра намеренно НЕ наши: [sp-16 .. sp-4] прерванного кода -
// спилл окон ABI, куда аппаратура кладёт регистры предка при переполнении
// окна, и обработчик переполнения читает оттуда указатель кадра. Кадр занимает
// [S-112 .. S), поэтому его верхние 16 байт приходятся ровно на эту область -
// так и должно быть: спилл пишет в кадр прерванной задачи, а не ниже него.
#define TF_A1       4
#define TF_A0       8
#define TF_PS       12
#define TF_PC       16
#define TF_SAR      20
#define TF_LBEG     24
#define TF_LEND     28
#define TF_LCOUNT   32
#define TF_A2       36
#define TF_A3       40
#define TF_A4       44
#define TF_A5       48
#define TF_A6       52
#define TF_A7       56
#define TF_A8       60
#define TF_A9       64
#define TF_A10      68
#define TF_A11      72
#define TF_A12      76
#define TF_A13      80
#define TF_A14      84
#define TF_A15      88

// 96 байт данных, выровненные до 16, плюс 16 под спилл окон.
#define TICK_FRAME 112

// --- кадр кооперативного переключателя ------------------------------------
//
// 48 байт, а не 32, как XT_SOL_FRMSZ у FreeRTOS. Причина - область спилла окон:
// при `entry a1, N` она занимает [N-16 .. N-4] нашего же кадра, и писать туда
// нельзя (см. правило про кадр). При N=32 под свои данные остаются 16 байт, а
// нам нужно шесть слов; при N=48 свои - 0..23, спилл - 32..44, и граница видна
// по самому числу.
#define SWITCH_FRAME 48

#define CF_A0       0    // адрес возврата вызывающего
#define CF_SAVE     4    // ctx уходящей: сюда пишется её sp
#define CF_LOAD     8    // ctx приходящей
#define CF_CURRENT  12   // адрес s_current
#define CF_NEXT     16   // номер приходящей задачи
#define CF_PS       20   // PS уходящей задачи: снят вызывающим до маски
#define CF_EPC1     24   // EPC1 на время сброса окон

// --- обмен с обработчиком тика -------------------------------------------
//
// Два поля в памяти, а не аргумент и возврат функции. Вызов из обработчика идёт
// через callx4 при CALLINC=0 в PS - ровно так же, как паника зовёт свой код, -
// и полагаться в этом месте на соглашение о регистрах возврата не хочется:
// ошибка выглядела бы как «после тика задача продолжила с мусором», а не как
// неверное значение. Память с кадром разойтись не может.
//
// Вход: кадр прерванной задачи (во что сохранить её sp). Выход: 0 - остаёмся в
// той же задаче, иначе указатель на контекст выбранной.
#define EX_FRAME    0
#define EX_NEXT     4

// --- PS на время работы обработчика --------------------------------------
//
// INTLEVEL = XCHAL_EXCM_LEVEL (3), UM, WOE, EXCM снят. Поднятый INTLEVEL - не
// перестраховка: снятие EXCM без него открыло бы прерывания (в том числе наш
// же тик), а обработчик не рассчитан на то, что его прервёт переключение.
// Ровно это же значение нужно и для сброса окон, и для вызова C из тика:
// состояние, в котором окна работают, а тик замаскирован, - одно.
#define PS_SPILL 0x00040023
