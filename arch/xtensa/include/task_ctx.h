//
// ЗАЧЕМ ОБЩИЙ ФАЙЛ. Кадр пишет один файл, а читает другой: кадр тика пишет
// vectors.S, а возобновляет по нему задачу tasks.S. Разъедутся смещения -
// ошибка будет выглядеть не как «не собралось», а как «задача продолжила с
// мусором в регистрах». Общий заголовок - единственное место, где каждое число
// написано один раз.
//
// Совпадение с C проверяется _Static_assert в arch/xtensa/tasks.c.

#pragma once

// --- контекст задачи (switch_ctx_t в tasks.c) -----------------------------
//
// Не «все регистры», а то, из чего задачу можно возобновить: подготовленный
// стек, PS, адреса функции и переходника. Всё остальное лежит в её кадрах на её
// стеке.
#define CTX_SP       0
