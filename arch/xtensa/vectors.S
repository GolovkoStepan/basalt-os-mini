// Своя таблица векторов.
//
// VECBASE не хранит младшие 10 бит адреса, поэтому таблица обязана начинаться
// на границе 1 КБ. Слоты - по 64 байта, смещения заданы архитектурой Xtensa,
// а не нами. Раскладку легко перепутать, поэтому она сверена с таблицей IDF
// (`_vector_table` в собранном образе), а не взята по памяти:
//
//   0x000  переполнение окна 4          0x200  прерывание уровня 4
//   0x040  недобор окна 4               0x240  прерывание уровня 5
//   0x080  переполнение окна 8          0x280  исключение отладки
//   0x0C0  недобор окна 8               0x2C0  NMI
//   0x100  переполнение окна 12         0x300  исключение ядра
//   0x140  недобор окна 12              0x340  пользовательское исключение
//   0x180  прерывание уровня 2          0x3C0  двойное исключение
//   0x1C0  прерывание уровня 3
//
// ОКНА РЕГИСТРОВ - НЕ ДЕТАЛЬ.
//
// Сборка идёт с оконным ABI: в коде есть `entry` и `retw`, а регистров a0..a15
// на всех не хватает - процессор держит 64 регистра и выдаёт их окнами по 16.
// Когда окно занято предком, а его регистр нужен потомку, аппаратура поднимает
// исключение «переполнение окна» и требует, чтобы обработчик сбросил старое
// окно на стек. Это происходит в обычной работе, а не только при сбоях.
//
// Проверено на плате: пока шесть слотов окон были заполнены нулями, первое же
// переполнение окна уходило в мусор, из мусора получалось двойное исключение,
// и плата молча висела. Симптом обманчивый - «сбой после инициализации
// таблицы», хотя таблица была права, а неполна.
//
// Обработчики окон - стандартные для Xtensa, по четыре-шестнадцать инструкций
// `s32e`/`l32e` плюс `rfwo`/`rfwu`. Своей логики здесь быть не должно: они
// выполняются в состоянии, где почти ничего нельзя, и любое отклонение от
// канона стоит молчаливого зависания.
//
// ГДЕ ЭТО ЛЕЖИТ И ПОЧЕМУ ТАМ.
//
// Блок размещается линкером прямо в IRAM (`.iram1`), с выравниванием на 1 КБ,
// и исполняется на месте - копирования нет.
//
// Копирование выглядело проще, но не работает: с включённой защитой памяти
// (CONFIG_ESP_SYSTEM_MEMPROT, по умолчанию включена) регион кода в IRAM
// защищён от записи, и попытка скопировать туда таблицу даёт LoadStoreError.
// Проверено на плате: EXCVADDR указывал ровно на буфер назначения. Отключать
// защиту памяти ради этого - лечить симптом: она понадобится, когда появятся
// задачи, а таблица векторов должна лежать в IRAM по-хорошему, как у IDF.
//
// Чтение из IRAM при этом разрешено - на этом IDF и держится: его слоты читают
// адрес таблицы обработчиков через литералы, лежащие в IRAM.
//
// Блок самодостаточен: ни одной внешней ссылки, кроме двух адресов в пуле -
// C-обработчика и вершины аварийного стека. Это важно, потому что собираем с
// -mlongcalls: `call0` и `movi` превратились бы в обращение к литералу в чужой
// секции, а такие литералы линкер кладёт рядом с кодом, но не гарантирует, что
// рядом с нашим.
//
// ПОЧЕМУ АВАРИЙНЫЙ СТЕК, А НЕ СТЕК СБОЯ.
//
// Кадр пишется на отдельный стек, а не на тот, что был в момент сбоя. Причина
// не в осторожности: первая же проверка на плате дала бесконечный цикл двойных
// исключений при сохранении кадра. Если сбой случился при испорченном или
// переполненном стеке, писать кадр «на место аварии» нельзя - каждое такое
// сохранение снова падает, и обработчик не печатает ничего. Свой стек делает
// отчёт независимым от состояния стека сбоя.
//
// КАК ВЫЗЫВАЕТСЯ C: ЧЕРЕЗ call4, И ЭТО НЕ ПРИХОТЬ.
//
// При PS.EXCM=1 переполнение окна не обслуживается, а сразу даёт двойное
// исключение. Поэтому перед вызовом C вход снимает EXCM, подняв INTLEVEL до
// XCHAL_EXCM_LEVEL (3), и прогоняет SPILL_ALL_WINDOWS - он опирается на те
// самые обработчики окон, что выше. Перед этим регистры a0..a5 возвращаются в
// состояние на момент сбоя: сброс окон пользуется ими как указателями на кадры
// предков, и мусор в них увёл бы запись в случайное место.
//
// Дальше - две вещи, каждая из которых проверена на плате:
//
//  1. `entry` в начале любой C-функции при EXCM=1 даёт двойное исключение.
//     Поэтому C вызывается с EXCM=0: PS как у IDF перед вызовом его
//     обработчика паники (INTLEVEL = XCHAL_DEBUGLEVEL-2 = 4, UM, WOE).
//  2. Вызов идёт через `callx4`, а не `call0`. call0 не поворачивает окно, и
//     тогда пролог вызываемой функции видит занятое окно - то есть требует
//     переполнения, которого после SPILL_ALL_WINDOWS быть не должно. call4
//     поворачивает окно, пролог получает свободное, и переполнения не
//     возникает. Первый аргумент при call4 передаётся в a6: регистры
//     вызываемого a2..a5 - это a6..a9 вызывающего.
//
// Указатели стека и регистров на момент сбоя сохраняются в EXCSAVE_1..5 -
// это единственная память, доступная до переезда на свой стек. EXCSAVE_n
// отданы в руки обработчику: аппаратура кладёт PC в EPC_n и EXCSAVE не трогает.

#include "xtensa/xt_specreg.h"

// Раскладка кадра. Она не обязана совпадать с XtExcFrame из IDF: кадр никто,
// кроме нас, не читает и не восстанавливает - из паники не возвращаются.
// Смещения обязаны совпадать с полями basalt_frame_t в panic.h; совпадение
// проверяется _Static_assert в panic.c.
#define FRAME_SIZE      112
#define FRAME_A0        0
#define FRAME_A1        4
#define FRAME_A2        8
#define FRAME_A3        12
#define FRAME_A4        16
#define FRAME_A5        20
#define FRAME_A6        24
#define FRAME_A7        28
#define FRAME_A15       60
#define FRAME_PS        64
#define FRAME_PC        68
#define FRAME_EXCCAUSE  72
#define FRAME_EXCVADDR  76
#define FRAME_SAR       80
#define FRAME_VECTOR    84

// PS для освобождения окон: INTLEVEL = 3 (XCHAL_EXCM_LEVEL), UM, WOE, EXCM снят.
// Уровень 3 - ровно тот, который маскировал EXCM, поэтому снятие EXCM не открывает
// прерывания, которые до сбоя были закрыты.
#define PS_SPILL  0x00040023
// PS перед вызовом C: EXCM снят, INTLEVEL = XCHAL_DEBUGLEVEL - 2 = 4.
// Ровно это значение ставит IDF перед вызовом своего обработчика паники.
#define PS_FOR_C  0x00040024

// Смещения адресов внутри таблицы. Каждое объявлено в одном месте и
// читается по нему же, иначе они разъедутся. Обязаны влезать в 8-битное
// смещение `l32i` (до 1020) и быть кратны 4.
#define HANDLER_POOL    0x3d8
#define EXC_STACK_POOL  0x3dc
#define NOTE_POOL       0x3e0

// Слот: спрятать по спецрегистрам то, что понадобится входу, и уйти в него.
.macro VEC_SLOT n
    wsr     a1, XT_REG_EXCSAVE_1
    wsr     a2, XT_REG_EXCSAVE_3
    wsr     a3, XT_REG_EXCSAVE_4
    wsr     a4, XT_REG_EXCSAVE_5
    movi    a2, \n
    j       basalt_vec_entry
.endm

    .section .iram1.basalt_vectors, "ax", @progbits
    .align  1024
    .global basalt_vectors
basalt_vectors:

// --- окна регистров -------------------------------------------------------
//
// Смысл одинаков во всех шести: потомок занял регистры, которые нужны предку,
// и аппаратура просит сбросить их в кадр предка на стеке. `s32e`/`l32e` пишут и
// читают по базе окна плюс смещение, не требуя отдельного указателя.

    // Переполнение окна 4: предок занимал четыре регистра из шестнадцати.
    .org    0x000
    s32e    a0, a5, -16
    s32e    a1, a5, -12
    s32e    a2, a5, -8
    s32e    a3, a5, -4
    rfwo

    // Недобор окна 4: возврат в кадр, чьи регистры были сброшены.
    .org    0x040
    l32e    a0, a5, -16
    l32e    a1, a5, -12
    l32e    a2, a5, -8
    l32e    a3, a5, -4
    rfwu

    // Переполнение окна 8. Кадр потомка - по a9, кадр предка ищется через a1
    // предка: адрес его вершины лежит в его же кадре по смещению -12.
    .org    0x080
    s32e    a0, a9, -16
    l32e    a0, a1, -12
    s32e    a1, a9, -12
    s32e    a2, a9, -8
    s32e    a3, a9, -4
    s32e    a4, a0, -32
    s32e    a5, a0, -28
    s32e    a6, a0, -24
    s32e    a7, a0, -20
    rfwo

    .org    0x0c0
    l32e    a0, a9, -16
    l32e    a1, a9, -12
    l32e    a2, a9, -8
    l32e    a7, a1, -12
    l32e    a3, a9, -4
    l32e    a4, a7, -32
    l32e    a5, a7, -28
    l32e    a6, a7, -24
    l32e    a7, a7, -20
    rfwu

    // Окно 12: кадр потомка - по a13, двенадцать регистров с шагом 4.
    .org    0x100
    s32e    a0, a13, -16
    l32e    a0, a1, -12
    s32e    a1, a13, -12
    s32e    a2, a13, -8
    s32e    a3, a13, -4
    s32e    a4, a0, -48
    s32e    a5, a0, -44
    s32e    a6, a0, -40
    s32e    a7, a0, -36
    s32e    a8, a0, -32
    s32e    a9, a0, -28
    s32e    a10, a0, -24
    s32e    a11, a0, -20
    rfwo

    .org    0x140
    l32e    a0, a13, -16
    l32e    a1, a13, -12
    l32e    a2, a13, -8
    l32e    a11, a1, -12
    l32e    a3, a13, -4
    l32e    a4, a11, -48
    l32e    a5, a11, -44
    l32e    a6, a11, -40
    l32e    a7, a11, -36
    l32e    a8, a11, -32
    l32e    a9, a11, -28
    l32e    a10, a11, -24
    l32e    a11, a11, -20
    rfwu

// --- прерывания и исключения ---------------------------------------------
//
// Все слоты ведут в один вход: различие между ними - только номер, а номер
// нужен лишь для отчёта.

    .org    0x180
    VEC_SLOT 2
    .org    0x1c0
    VEC_SLOT 3
    .org    0x200
    VEC_SLOT 4
    .org    0x240
    VEC_SLOT 5
    .org    0x280
    VEC_SLOT 6
    .org    0x2c0
    VEC_SLOT 7

    // Исключение ядра (сюда же прерывания уровня 1) и пользовательское.
    .org    0x300
    VEC_SLOT 8
    .org    0x340
    VEC_SLOT 9

    // Двойное исключение: сбой внутри обработчика. Если не сработает и этот
    // слот, процессор уйдёт в тройное исключение, а из него - в сброс без
    // единой строки в консоли.
    .org    0x3c0
    VEC_SLOT 10

    // Два адреса, которые нужны входу и телу. Лежат внутри таблицы не из
    // экономии места, а чтобы у блока не было ссылок наружу: база берётся из
    // VECBASE, смещение известно ассемблеру. Так переход не зависит от того,
    // где линкер разместил остальной код.
    .org    HANDLER_POOL
basalt_handler_pool:
    .word   basalt_panic_exc

    .org    EXC_STACK_POOL
    .word   basalt_exc_stack_top

    .org    NOTE_POOL
    .word   basalt_vec_note

    .org    0x400
basalt_vectors_table_end:

// Общий вход: кадр на аварийном стеке, освобождение окон, и только потом
// C. Регистры a2..a4 к этому моменту спрятаны в EXCSAVE_3..5.
basalt_vec_entry:
    // Переезд на аварийный стек. Кадр кладём внутрь блока, а не над вершиной:
    // над вершиной уже чужая память.
    rsr     a1, XT_REG_VECBASE
    movi    a3, EXC_STACK_POOL
    add     a1, a1, a3
    l32i    a1, a1, 0
    addi    a1, a1, -FRAME_SIZE
    j       basalt_vec_body

// Тело: сохранить всё, что нужно для отчёта, освободить окна и уйти в C.
basalt_vec_body:
    s32i    a0, a1, FRAME_A0
    s32i    a5, a1, FRAME_A5
    s32i    a6, a1, FRAME_A6
    s32i    a7, a1, FRAME_A7
    s32i    a8, a1, 32
    s32i    a9, a1, 36
    s32i    a10, a1, 40
    s32i    a11, a1, 44
    s32i    a12, a1, 48
    s32i    a13, a1, 52
    s32i    a14, a1, 56
    s32i    a15, a1, FRAME_A15

    // a1..a4 в кадр - из спецрегистров: в самих регистрах уже наши значения.
    rsr     a5, XT_REG_EXCSAVE_1
    s32i    a5, a1, FRAME_A1
    rsr     a5, XT_REG_EXCSAVE_3
    s32i    a5, a1, FRAME_A2
    rsr     a5, XT_REG_EXCSAVE_4
    s32i    a5, a1, FRAME_A3
    rsr     a5, XT_REG_EXCSAVE_5
    s32i    a5, a1, FRAME_A4

    // Номер слота. Он в a2, потому что a2 уже сохранён выше.
    s32i    a2, a1, FRAME_VECTOR

    rsr     a5, XT_REG_PS
    s32i    a5, a1, FRAME_PS
    rsr     a5, XT_REG_EPC_1
    s32i    a5, a1, FRAME_PC
    rsr     a5, XT_REG_EXCCAUSE
    s32i    a5, a1, FRAME_EXCCAUSE
    rsr     a5, XT_REG_EXCVADDR
    s32i    a5, a1, FRAME_EXCVADDR
    rsr     a5, XT_REG_SAR
    s32i    a5, a1, FRAME_SAR

    // Вернуть a0..a5 в состояние на момент сбоя: сброс окон пользуется ими как
    // указателями на кадры предков, и мусор в них увёл бы запись в случайное
    // место. Значения кадра при этом не теряются - они уже в памяти.
    l32i    a0, a1, FRAME_A0
    l32i    a2, a1, FRAME_A2
    l32i    a3, a1, FRAME_A3
    l32i    a4, a1, FRAME_A4
    l32i    a5, a1, FRAME_A5
    l32i    a1, a1, FRAME_A1         // стек на момент сбоя, как в обычной работе

    // Снять EXCM на время сброса окон: при EXCM=1 переполнение окна сразу
    // даёт двойное исключение, и сбросить нечего не выйдет.
    movi    a6, PS_SPILL
    wsr     a6, XT_REG_PS
    rsync

    // SPILL_ALL_WINDOWS: тронуть регистр чужого окна, дать аппаратуре сбросить
    // его через обработчик переполнения, повернуть окно, повторить. Ровно так
    // же это делает IDF; короче и надёжнее не получается, потому что сами
    // сбросы делает железо.
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    4

    // Окна сброшены - можно звать C. Прерывания закрываем совсем: паника не
    // возвращается, а вложенное прерывание только испортит отчёт.
    movi    a5, 0
    wsr     a5, XT_REG_INTENABLE

    // PS для вызова C - ровно как у IDF перед вызовом своего обработчика
    // паники: EXCM снят, INTLEVEL = XCHAL_DEBUGLEVEL - 2 = 4, UM и WOE как в
    // обычном оконном коде. EXCM снимать обязательно: `entry` в начале любой
    // C-функции при EXCM=1 даёт двойное исключение - проверено на плате.
    movi    a5, PS_FOR_C
    wsr     a5, XT_REG_PS
    rsync

    // Кадр снова адресуем: после поворотов окна a1 указывал на стек сбоя.
    rsr     a1, XT_REG_VECBASE
    movi    a3, EXC_STACK_POOL
    add     a1, a1, a3
    l32i    a1, a1, 0
    addi    a1, a1, -FRAME_SIZE

    // Вызов через callx4, а не call0: call4 поворачивает окно, поэтому пролог
    // вызываемой функции получает свободное окно и обходится без
    // переполнения. Первый аргумент при этом передаётся в a6 - так устроен
    // call4: регистры вызываемого a2..a5 - это a6..a9 вызывающего.
    rsr     a3, XT_REG_VECBASE
    l32i    a4, a3, NOTE_POOL
    mov     a6, a1
    callx4  a4

    // Дальше - полный разбор паники, он не возвращается. Кадр адресуем заново:
    // после callx4 окно повернулось обратно, но a1 надёжнее взять из пула.
    rsr     a1, XT_REG_VECBASE
    movi    a3, EXC_STACK_POOL
    add     a1, a1, a3
    l32i    a1, a1, 0
    addi    a1, a1, -FRAME_SIZE
    rsr     a3, XT_REG_VECBASE
    l32i    a4, a3, HANDLER_POOL
    mov     a6, a1
    callx4  a4

    .global basalt_vectors_end
basalt_vectors_end:

// Аварийный стек. Лежит в DRAM: в IRAM писать нельзя (защита памяти), а стек
// по определению пишется. Размер - с запасом на панику и её печать.
// Вложенных исключений не боимся: каждое начинается с той же вершины, поэтому
// цикл двойных исключений не съедает стек, а повторяет один и тот же кадр.
    .section .bss.basalt_exc_stack, "aw", @nobits
    .align  16
basalt_exc_stack_bottom:
    .space  8192
    .global basalt_exc_stack_top
basalt_exc_stack_top:
