// Переключение задач: сброс окон и смена стека. Только ассемблер.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ НИ ОДНОЙ ФУНКЦИИ C.
//
// Смена указателя стека не терпит пролога: `entry` в начале C-функции уже
// выделил кадр на старом стеке, и после смены a1 этот кадр оказался бы в чужой
// памяти. Поэтому сайт переключения - отдельная функция, и после смены стека в
// ней не остаётся ничего живого.
//
// ПОЧЕМУ СНАЧАЛА СПИЛЛ, А ПОТОМ СМЕНА СТЕКА.
//
// У Xtensa оконный ABI: одновременно живы несколько окон по 16 регистров, и
// регистры вызывающего лежат в физическом файле, а не на стеке. Пока окна не
// сброшены, они принадлежат тому, кто работает сейчас. Поэтому порядок
// строгий: сначала SPILL_ALL_WINDOWS раскладывает живые окна по кадрам на
// стеке задачи, и только потом можно менять стек.
//
// Обратный порядок означал бы сброс окон одной задачи в стек другой. Это не
// гипотеза: та же ошибка, только меньшего размера, уже была на шаге 1 - кадр,
// положенный ниже SP, затёр спилл окон, и падение случалось в одном прогоне
// из трёх.
//
// ПОЧЕМУ СОХРАНЯЮТСЯ ВСЕГО ДВА ЧИСЛА.
//
// В оконном ABI у каждой функции своё окно, и a1 - регистр этого окна. Адрес
// возврата вызывающего уже лежит в его кадре на его стеке (его положил
// `entry`), а регистры сброшены спиллом. Значит контекст задачи - это указатель
// стека и PS. Регистры a0..a15 нашего окна сохранять не нужно: после `retw`
// это окно отбрасывается целиком.
//
// WINDOWSTART НЕ СОХРАНЯЕТСЯ И НЕ ВОССТАНАВЛИВАЕТСЯ - И ЭТО ПРАВИЛЬНО.
//
// Соблазн сохранить его на задачу есть, и он был сделан - после чего плата
// замолкала ровно при возврате. Причина в том, что retw и обработчики
// переполнения/недобора - это единый механизм: спилл оставляет живым одно
// текущее окно, а retw возвращается в окно предка через недобор и восстанавливает
// регистры из его кадра на стеке задачи. Подсовывать сюда готовую маску значит
// обойти механизм, который эти же кадры и обслуживает. FreeRTOS в
// _frxt_dispatch_sol не трогает WINDOWSTART по той же причине.
//
// ЭТАЛОН. Порядок и раскладка кадра взяты из vPortYield и _frxt_dispatch в
// portable/xtensa/portasm.S, спилл - из _xt_context_save в
// components/xtensa/xtensa_context.S. Этот код проверен на этой же плате
// миллионами запусков FreeRTOS; отступать от него в самом опасном месте
// незачем. Отличия от эталона ровно два: нет threadptr (мы его не используем)
// и нет сопроцессоров (их у нас нет).

    .section .iram1.basalt_tasks, "ax", @progbits

// Раскладки, общие с vectors.S: контекст задачи, кадр переключателя, PS для
// сброса окон. Подключаются, а не дублируются: кадр пишет этот файл, а
// возобновляет после вытеснения vectors.S, и разъехавшиеся смещения дают не
// ошибку сборки, а мусор в регистрах на плате.
#include "task_ctx.h"
#include "xtensa/xt_specreg.h"

// PS на время сброса окон - в task_ctx.h, там же объяснение.

// void basalt_task_switch(uint32_t* save_sp, switch_ctx_t* load,
//                         size_t* current_slot, size_t next, uint32_t ps)
//
// a2 - куда записать указатель стека уходящей задачи (первое поле её ctx)
// a3 - контекст задачи, которая должна продолжить
// a4 - адрес s_current: туда пишется номер приходящей задачи
// a5 - номер приходящей задачи
// a6 - PS уходящей задачи, снятый вызывающим ДО маскирования тика
    .global basalt_task_switch
    .type   basalt_task_switch, @function
    .align  4
basalt_task_switch:
    entry   a1, SWITCH_FRAME
    s32i    a0, a1, CF_A0        // адрес возврата: им же и вернёмся
    s32i    a2, a1, CF_SAVE      // ctx уходящей
    s32i    a3, a1, CF_LOAD      // ctx приходящей
    s32i    a4, a1, CF_CURRENT   // адрес s_current
    s32i    a5, a1, CF_NEXT      // номер приходящей
    s32i    a6, a1, CF_PS        // PS уходящей: снят до маски, см. ниже

    // PS уходящей задачи приходит аргументом, а не читается здесь.
    //
    // Читать его тут нельзя: вызывающий (switch_to) уже поднял INTLEVEL, чтобы
    // тик не влез в правку таблицы, и `rsr PS` вернул бы замаскированный
    // уровень. Задача возобновилась бы с INTLEVEL=3 - то есть без тика вообще,
    // и вытеснение в системе навсегда выключилось бы после первого yield.
    //
    // Маска эта - `rsil`, а не гашение линии в INTENABLE, и это важно:
    // INTENABLE общий для процессора, и снятый в нём бит остался бы снятым и
    // после ухода в другую задачу. INTLEVEL же восстанавливается вместе с PS
    // задачи, поэтому следующий код получает свою маску, а не чужую.
    // Своего `rsil` здесь нет: маску уже держит вызывающий.

    // --- сброс окон ---
    // EXCM снимается, INTLEVEL поднимается: при EXCM=1 переполнение окна сразу
    // даёт двойное исключение, то есть сбрасывать нечем. EPC1 сохраняем - его
    // затрут обработчики переполнения.
    rsr     a5, EPC1
    s32i    a5, a1, CF_EPC1
    movi    a5, PS_SPILL
    wsr     a5, PS
    rsync

    // Пять поворотов по три и один на четыре - все окна файла. Это макрос
    // SPILL_ALL_WINDOWS из xt_asm_utils.h, выписанный явно: наш файл
    // собирается без include-путей IDF, и зависеть от внутреннего заголовка в
    // самом опасном месте не хочется.
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    4

    // EPC1 возвращаем: его испортили обработчики окон. PS пока не трогаем -
    // он намеренно остаётся маскирующим до самого возврата, иначе прерывание
    // успело бы прийти между сбросом окон и сменой стека.
    l32i    a5, a1, CF_EPC1
    wsr     a5, EPC1
    rsync

    // --- сохранить уходящую задачу ---
    //
    // PS берётся из кадра, куда его положил вызывающий. Ничего в нём не
    // правится: замеренный PS = 0x00060722, то есть WOE=1, UM=1, CALLINC=2,
    // INTLEVEL=2 - ровно рабочее состояние оконного режима. Любая
    // «нормализация» здесь означала бы, что задача продолжит в другом режиме,
    // чем шла.
    //
    // Отдельно про ловушку чтения: `tickrate` ОДНАЖДЫ печатал PS десятичным
    // числом после «0x», и 0x395042 в логе было прочитано как PS с WOE=0,
    // хотя настоящий PS был 0x60722. Один раз на этом уже был сделан неверный
    // вывод, и правка чуть не уехала в код. Сейчас hex печатает out_hex.
    l32i    a2, a1, CF_SAVE
    s32i    a1, a2, CTX_SP
    l32i    a3, a1, CF_PS
    s32i    a3, a2, CTX_PS

    // Кадр кооперативный - и пометка об этом ставится здесь же, под маской.
    //
    // В C это делать нельзя: тик может прийти между обнулением пометки и
    // вызовом, поставить свою (1) и уйти в другую задачу; когда эта задача
    // вернётся, она вызвала бы переключатель и получила кооперативный кадр с
    // пометкой «остановлена тиком» - то есть возврат через `rfi 3` в кадр, к
    // прерыванию не относящийся.
    //
    // Заодно это делает кадр самодостаточным: кто написал кадр, тот и сказал,
    // как в него возвращаться.
    movi    a5, 0
    s32i    a5, a2, CTX_PREEMPT
    // --- s_current ---
    //
    // Номер приходящей задачи записывается здесь, а не в C перед вызовом:
    // начиная с этой строки тик (если он придёт) будет искать на процессоре уже
    // новую задачу, и это правда - уходящая сохранена целиком, стек её здесь
    // больше не нужен.
    //
    // И наоборот, записать его в C ДО вызова нельзя: тик в зазоре сохранил бы
    // кадр на стеке уходящей задачи и записал бы его в контекст приходящей,
    // то есть задача продолжила бы с чужим стеком. Ошибка была бы тихой и не
    // каждый раз - поэтому номер идёт аргументом сюда, под маску.
    //
    // PS по-прежнему маскирующий: тик не может прийти между записью s_current и
    // сменой стека.
    l32i    a2, a1, CF_CURRENT
    l32i    a3, a1, CF_NEXT
    s32i    a3, a2, 0

    // --- восстановить приходящую ---
    //
    // Дальше общий путь возобновления: он же зовётся из обработчика тика, когда
    // тик выбрал другую задачу. Один код на три случая - иначе «вернуться в
    // задачу» пришлось бы держать в двух местах, и они разошлись бы на первом
    // же исправлении.
    l32i    a2, a1, CF_LOAD
    j       basalt_task_resume

    .size   basalt_task_switch, . - basalt_task_switch

// Возобновить задачу по её контексту. Не возвращается.
//
// Вход: a2 - ctx задачи, в которую надо войти.
//
// Три случая, и различаются они только способом возврата:
//
//   1. задача ещё не начиналась - вход настоящим callx8 (см. комментарий ниже);
//   2. задача остановлена тиком - восстановить кадр тика и `rfi 3`;
//   3. задача отдала процессор сама - `retw` в её кадр переключателя.
//
// Зовётся и из basalt_task_switch (по `j`, не вызовом), и из обработчика тика.
// Вызовом её звать нельзя: она меняет стек и не возвращается, а пролог вызова
// положил бы кадр на стек покидаемой задачи.
    .global basalt_task_resume
    .type   basalt_task_resume, @function
    .align  4
basalt_task_resume:
    l32i    a5, a2, CTX_START
    bnez    a5, .Lfirst_entry

    l32i    a5, a2, CTX_PREEMPT
    bnez    a5, .Lresume_preempt

    // --- возврат в задачу, отдавшую процессор ---
    //
    // sp перед retw НЕ правится, и это не упущение. `retw` в оконном ABI сам
    // возвращает вызывающему его окно вместе с его a1: a1 - регистр окна, и
    // при повороте окна на место встаёт значение вызывающего. Поэтому и весь
    // скомпилированный код заканчивается `retw.n` без единого `addi sp` перед
    // ним, и FreeRTOS в _frxt_dispatch_sol делает то же самое (addi sp там
    // только в ветке CALL0 ABI).
    //
    // ВАЖНО: сюда не попадает вытеснение. Тик не возобновляет задачу с
    // кооперативным кадром - проверено на плате, что возврат из прерывания в
    // такой кадр падает (см. basalt_task_preempt). Поэтому `retw` здесь
    // выполняется только в том же окне, в каком задача отдала процессор.
    //
    // Чинить это возвратом базы и маски окон пробовали трижды, и все три раза
    // плата падала: `retw` после `rfi` в чужой кадр не спасают ни PS.OWB,
    // ни WINDOWSTART (подробности и номера опытов - в basalt_task_preempt).
    // WINDOWBASE нельзя записать напрямую: его задаёт только `rfi` (из PS.OWB)
    // или `rotw`. Отсюда вывод: кадр должен быть один - кадр тика.
    l32i    a1, a2, CTX_SP
    l32i    a0, a1, 0
    l32i    a4, a2, CTX_PS
    wsr     a4, PS
    rsync
    retw

    // --- возврат в задачу, остановленную тиком ---
    //
    // Кадр тика - полный: помимо регистров в нём лежат PS, PC и SAR с
    // регистрами циклов. PS уходит в EPS_3, PC - в EPC_3, a0 - в EXCSAVE_3:
    // именно оттуда `rfi 3` их и забирает. Это единственное место, где
    // восстанавливается чужая задача с чужого стека, поэтому порядок жёсткий:
    // сперва спецрегистры, потом регистры окна, и последним a1 - после него
    // кадр недоступен.
    //
    // PS несёт в себе и базу окон (PS.OWB). Поэтому `rfi` возвращает не только
    // режим прерванной задачи, но и её окно - отдельно WINDOWBASE
    // восстанавливать не нужно и нельзя.
.Lresume_preempt:
    l32i    a1, a2, CTX_SP

    l32i    a4, a1, TF_SAR
    wsr     a4, SAR
    l32i    a4, a1, TF_LBEG
    wsr     a4, LBEG
    l32i    a4, a1, TF_LEND
    wsr     a4, LEND
    l32i    a4, a1, TF_LCOUNT
    wsr     a4, LCOUNT

    l32i    a4, a1, TF_A0
    wsr     a4, XT_REG_EXCSAVE_3
    l32i    a4, a1, TF_PS
    wsr     a4, XT_REG_EPS_3
    l32i    a4, a1, TF_PC
    wsr     a4, XT_REG_EPC_3

    l32i    a2, a1, TF_A2
    l32i    a3, a1, TF_A3
    l32i    a4, a1, TF_A4
    l32i    a5, a1, TF_A5
    l32i    a6, a1, TF_A6
    l32i    a7, a1, TF_A7
    l32i    a8, a1, TF_A8
    l32i    a9, a1, TF_A9
    l32i    a10, a1, TF_A10
    l32i    a11, a1, TF_A11
    l32i    a12, a1, TF_A12
    l32i    a13, a1, TF_A13
    l32i    a14, a1, TF_A14
    l32i    a15, a1, TF_A15

    l32i    a1, a1, TF_A1

    // `rsync` перед `rfi` обязателен: без него запись EPS_3/EPC_3 и
    // восстановление регистров могут не вступить в силу до возврата.
    rsync
    rfi     3

    // --- первый вход в задачу ---
    //
    // ПЕРВЫЙ ВХОД В ЗАДАЧУ - НАСТОЯЩИМ callx8.
    //
    // Здесь была ошибка, которая стоила вечера: новую задачу «перепрыгивали»
    // через `jx` в переходник. Это работает ровно до первого вызова внутри
    // задачи. Цепочку звеньев окон строят аппаратура и обработчики
    // переполнения, а указатель стека предка лежит в кадре потомка по
    // смещению -12. При переходе предка нет, и обработчик переполнения пишет
    // регистры по закраске стека (EXCVADDR 0xC3C3C3A3), то есть в никуда.
    //
    // Поэтому стек задачи готовит basalt_task_create - с областью звена, как
    // SET_STACK из xt_instr_macros.h, - а вход делает обычный вызов: он сам
    // поворачивает окно и передаёт вызываемому a9 = a1.
.Lfirst_entry:
    l32i    a1, a2, CTX_SP
    l32i    a4, a2, CTX_PS

    // Отметку «ещё не начиналась» снимаем здесь: вход в задачу не возвращается,
    // и C не получит управления, чтобы это сделать.
    movi    a5, 0
    s32i    a5, a2, CTX_START

    // Аргументы вызываемого при callx8 приходят из a10..a15.
    l32i    a10, a2, CTX_ARG
    l32i    a11, a2, CTX_FN
    l32i    a8, a2, CTX_ENTRY

    wsr     a4, PS
    rsync

    mov     a9, a1               // указатель стека для окна вызываемого
    callx8  a8

    // Переходник не возвращается: задача либо отдаёт процессор, либо
    // завершается через basalt_task_exit. Если управление всё же пришло сюда,
    // продолжать нельзя - здесь чужой стек и мёртвое окно.
1:
    j       1b

    .size   basalt_task_resume, . - basalt_task_resume

// Переходник между переключателем и функцией задачи.
//
// Задача - это не «перейти в функцию»: функция вернётся, а возвращаться будет
// некуда. Переходник зовёт функцию задачи, а после её возврата закрывает
// задачу.
//
// Вход: a2 - аргумент, a3 - функция (при call8 аргументы вызывающего уходят в
// a10..a15 и приходят сюда как a2..a7).
    .global basalt_task_trampoline
    .type   basalt_task_trampoline, @function
    .align  4
basalt_task_trampoline:
    // Свой кадр нужен: вошли вызовом, окно повёрнуто.
    //
    // Данные кладём в ПЕРВЫЕ 16 байт кадра. Верхние 16 байт - область, куда
    // аппаратура кладёт регистры вызывающего при переполнении окна; писать
    // туда нельзя даже здесь, где вызывающего нет: она считается её.
    entry   a1, SWITCH_FRAME
    s32i    a2, a1, 0            // аргумент
    s32i    a3, a1, 4            // функция

    l32i    a10, a1, 0           // аргумент -> a2 вызываемого
    l32i    a8, a1, 4            // функция
    mov     a9, a1               // указатель стека для окна вызываемого
    callx8  a8

    // Функция вернулась - задача закончена. exit не возвращается.
    movi    a10, basalt_task_exit
    mov     a9, a1
    callx8  a10
1:
    j       1b

    .size   basalt_task_trampoline, . - basalt_task_trampoline
