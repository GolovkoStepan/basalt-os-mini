// Переключение задач: сброс окон и смена стека. Только ассемблер.
//
// ПОЧЕМУ ЗДЕСЬ НЕТ НИ ОДНОЙ ФУНКЦИИ C.
//
// Смена указателя стека не терпит пролога: `entry` в начале C-функции уже
// выделил кадр на старом стеке, и после смены a1 этот кадр оказался бы в чужой
// памяти. Поэтому сайт переключения - отдельная функция, и после смены стека в
// ней не остаётся ничего живого.
//
// ПОЧЕМУ СНАЧАЛА СПИЛЛ, А ПОТОМ СМЕНА СТЕКА.
//
// У Xtensa оконный ABI: одновременно живы несколько окон по 16 регистров, и
// регистры вызывающего лежат в физическом файле, а не на стеке. Пока окна не
// сброшены, они принадлежат тому, кто работает сейчас. Поэтому порядок
// строгий: сначала SPILL_ALL_WINDOWS раскладывает живые окна по кадрам на
// стеке задачи, и только потом можно менять стек.
//
// Обратный порядок означал бы сброс окон одной задачи в стек другой. Это не
// гипотеза: та же ошибка, только меньшего размера, уже была на шаге 1 - кадр,
// положенный ниже SP, затёр спилл окон, и падение случалось в одном прогоне
// из трёх.
//
// ПОЧЕМУ СОХРАНЯЮТСЯ ВСЕГО ДВА ЧИСЛА.
//
// В оконном ABI у каждой функции своё окно, и a1 - регистр этого окна. Адрес
// возврата вызывающего уже лежит в его кадре на его стеке (его положил
// `entry`), а регистры сброшены спиллом. Значит контекст задачи - это указатель
// стека и PS. Регистры a0..a15 нашего окна сохранять не нужно: после `retw`
// это окно отбрасывается целиком.
//
// WINDOWSTART НЕ СОХРАНЯЕТСЯ И НЕ ВОССТАНАВЛИВАЕТСЯ - И ЭТО ПРАВИЛЬНО.
//
// Соблазн сохранить его на задачу есть, и он был сделан - после чего плата
// замолкала ровно при возврате. Причина в том, что retw и обработчики
// переполнения/недобора - это единый механизм: спилл оставляет живым одно
// текущее окно, а retw возвращается в окно предка через недобор и восстанавливает
// регистры из его кадра на стеке задачи. Подсовывать сюда готовую маску значит
// обойти механизм, который эти же кадры и обслуживает. FreeRTOS в
// _frxt_dispatch_sol не трогает WINDOWSTART по той же причине.
//
// ЭТАЛОН. Порядок и раскладка кадра взяты из vPortYield и _frxt_dispatch в
// portable/xtensa/portasm.S, спилл - из _xt_context_save в
// components/xtensa/xtensa_context.S. Этот код проверен на этой же плате
// миллионами запусков FreeRTOS; отступать от него в самом опасном месте
// незачем. Отличия от эталона ровно два: нет threadptr (мы его не используем)
// и нет сопроцессоров (их у нас нет).

    .section .iram1.basalt_tasks, "ax", @progbits

// Раскладка switch_ctx_t (arch/xtensa/tasks.c). Сверяется _Static_assert там
// же; здесь продублирована, потому что ассемблер не читает C-структуры.
#define CTX_SP       0
#define CTX_PS       4
#define CTX_START    8
#define CTX_FN       12
#define CTX_ARG      16
#define CTX_ENTRY    20

// Размер кадра переключателя. 32 - тот же XT_SOL_FRMSZ, что у FreeRTOS:
// 16 байт своих данных плюс 16 байт области, куда `entry` кладёт указатель
// кадра вызывающего.
#define SWITCH_FRAME 32

// PS на время сброса окон: INTLEVEL=3 (XCHAL_EXCM_LEVEL), UM, WOE, EXCM снят.
// Поднятый INTLEVEL - не перестраховка: снятие EXCM без него открыло бы тик, а
// обработчик тика не рассчитан на то, что его прервёт переключение.
//
// Это единственная константа PS в файле, и она того заслуживает: здесь значение
// не «режим задачи», а «состояние, в котором можно сбрасывать окна», и оно
// одинаково для любой задачи.
#define PS_SPILL     0x00040023

// void basalt_task_switch(uint32_t* save_sp, switch_ctx_t* load)
//
// a2 - куда записать указатель стека уходящей задачи (первое поле её ctx)
// a3 - контекст задачи, которая должна продолжить
    .global basalt_task_switch
    .type   basalt_task_switch, @function
    .align  4
basalt_task_switch:
    entry   a1, SWITCH_FRAME
    s32i    a0, a1, 0            // адрес возврата: им же и вернёмся
    s32i    a2, a1, 4            // ctx уходящей
    s32i    a3, a1, 8            // ctx приходящей

    // PS уходящей задачи - ДО маскирования: в нём её рабочий INTLEVEL, и
    // именно его надо вернуть этой задаче при следующем входе.
    rsr     a4, PS
    rsil    a6, 3

    // --- сброс окон ---
    // EXCM снимается, INTLEVEL поднимается: при EXCM=1 переполнение окна сразу
    // даёт двойное исключение, то есть сбрасывать нечем. EPC1 сохраняем - его
    // затрут обработчики переполнения.
    rsr     a5, EPC1
    s32i    a5, a1, 12
    movi    a5, PS_SPILL
    wsr     a5, PS
    rsync

    // Пять поворотов по три и один на четыре - все окна файла. Это макрос
    // SPILL_ALL_WINDOWS из xt_asm_utils.h, выписанный явно: наш файл
    // собирается без include-путей IDF, и зависеть от внутреннего заголовка в
    // самом опасном месте не хочется.
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    3
    and     a12, a12, a12
    rotw    4

    // EPC1 возвращаем: его испортили обработчики окон. PS пока не трогаем -
    // он намеренно остаётся маскирующим до самого возврата, иначе прерывание
    // успело бы прийти между сбросом окон и сменой стека.
    l32i    a5, a1, 12
    wsr     a5, EPC1
    rsync

    // --- сохранить уходящую задачу ---
    //
    // PS сохраняется из a4 - снимок, сделанный ДО маскирования. Ничего в нём
    // не правится: замеренный PS = 0x00060722, то есть WOE=1, UM=1,
    // CALLINC=2, INTLEVEL=2 - ровно рабочее состояние оконного режима. Любая
    // «нормализация» здесь означала бы, что задача продолжит в другом режиме,
    // чем шла.
    //
    // Отдельно про ловушку чтения: `tickrate` ОДНАЖДЫ печатал PS десятичным
    // числом после «0x», и 0x395042 в логе было прочитано как PS с WOE=0,
    // хотя настоящий PS был 0x60722. Один раз на этом уже был сделан неверный
    // вывод, и правка чуть не уехала в код. Сейчас hex печатает out_hex.
    l32i    a2, a1, 4
    s32i    a1, a2, CTX_SP
    s32i    a4, a2, CTX_PS

    // --- восстановить приходящую ---
    l32i    a3, a1, 8
    l32i    a5, a3, CTX_START
    beqz    a5, .Lresume

    // ПЕРВЫЙ ВХОД В ЗАДАЧУ - НАСТОЯЩИМ callx8.
    //
    // Здесь была ошибка, которая стоила вечера: новую задачу «перепрыгивали»
    // через `jx` в переходник. Это работает ровно до первого вызова внутри
    // задачи. Цепочку звеньев окон строят аппаратура и обработчики
    // переполнения, а указатель стека предка лежит в кадре потомка по
    // смещению -12. При переходе предка нет, и обработчик переполнения пишет
    // регистры по закраске стека (EXCVADDR 0xC3C3C3A3), то есть в никуда.
    //
    // Поэтому стек задачи готовит basalt_task_create - с областью звена, как
    // SET_STACK из xt_instr_macros.h, - а вход делает обычный вызов: он сам
    // поворачивает окно и передаёт вызываемому a9 = a1.
    l32i    a1, a3, CTX_SP
    l32i    a4, a3, CTX_PS

    // Отметку «ещё не начиналась» снимаем здесь: переключение в задачу не
    // возвращается, и C не получит управления, чтобы это сделать.
    movi    a6, 0
    s32i    a6, a3, CTX_START

    // Аргументы вызываемого при callx8 приходят из a10..a15.
    l32i    a10, a3, CTX_ARG
    l32i    a11, a3, CTX_FN
    l32i    a8, a3, CTX_ENTRY

    wsr     a4, PS
    rsync

    mov     a9, a1               // указатель стека для окна вызываемого
    callx8  a8

    // Переходник не возвращается: задача либо отдаёт процессор, либо
    // завершается через basalt_task_exit. Если управление всё же пришло сюда,
    // продолжать нельзя - здесь чужой стек и мёртвое окно.
1:
    j       1b

.Lresume:
    // Задача продолжает ровно с той точки, где ушла: её кадр - это кадр этого
    // же переключателя в прошлый раз.
    //
    // sp перед retw НЕ правится, и это не упущение. `retw` в оконном ABI сам
    // возвращает вызывающему его окно вместе с его a1: a1 - регистр окна, и
    // при повороте окна на место встаёт значение вызывающего. Поэтому и весь
    // скомпилированный код заканчивается `retw.n` без единого `addi sp` перед
    // ним, и FreeRTOS в _frxt_dispatch_sol делает то же самое (addi sp там
    // только в ветке CALL0 ABI).
    l32i    a1, a3, CTX_SP
    l32i    a0, a1, 0
    l32i    a4, a3, CTX_PS
    wsr     a4, PS
    rsync
    retw

    .size   basalt_task_switch, . - basalt_task_switch

// Переходник между переключателем и функцией задачи.
//
// Задача - это не «перейти в функцию»: функция вернётся, а возвращаться будет
// некуда. Переходник зовёт функцию задачи, а после её возврата закрывает
// задачу.
//
// Вход: a2 - аргумент, a3 - функция (при call8 аргументы вызывающего уходят в
// a10..a15 и приходят сюда как a2..a7).
    .global basalt_task_trampoline
    .type   basalt_task_trampoline, @function
    .align  4
basalt_task_trampoline:
    // Свой кадр нужен: вошли вызовом, окно повёрнуто.
    //
    // Данные кладём в ПЕРВЫЕ 16 байт кадра. Верхние 16 байт - область, куда
    // аппаратура кладёт регистры вызывающего при переполнении окна; писать
    // туда нельзя даже здесь, где вызывающего нет: она считается её.
    entry   a1, SWITCH_FRAME
    s32i    a2, a1, 0            // аргумент
    s32i    a3, a1, 4            // функция

    l32i    a10, a1, 0           // аргумент -> a2 вызываемого
    l32i    a8, a1, 4            // функция
    mov     a9, a1               // указатель стека для окна вызываемого
    callx8  a8

    // Функция вернулась - задача закончена. exit не возвращается.
    movi    a10, basalt_task_exit
    mov     a9, a1
    callx8  a10
1:
    j       1b

    .size   basalt_task_trampoline, . - basalt_task_trampoline
