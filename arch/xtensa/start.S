// Своя точка входа. Зачем своя - см. start.h.
//
// Здесь только ассемблер, потому что менять указатель стека из C нельзя: пока
// компилятор считает, что локальные переменные лежат по старому указателю,
// любая функция ниже по течению будет писать в чужую память. Перенос стека
// обязан быть отдельной функцией, в которой на старом стеке не остаётся
// ничего живого.

    .section .bss.basalt_stack, "aw", @nobits
    .align  16
basalt_stack_bottom:
    // 8 КБ. Самый жадный пользователь - паника: она печатает дамп через
    // свою же консоль, и на этот путь уходит несколько сотен байт.
    .space  8192
basalt_stack_top:

    .section .text.basalt_start, "ax"
    .align  4
    .global basalt_start
    .type   basalt_start, @function
basalt_start:
    // Переезд на свой стек. Чужой стек загрузчика нам ни к чему: его размер
    // задан не нами, и на нём уже лежат чужие кадры.
    movi    a1, basalt_stack_top

    // И сразу в C, откуда возврата нет.
    call0   basalt_main

    // Страховка: если basalt_main всё-таки вернётся, стоим здесь, а не
    // проваливаемся в неизвестный код следом.
1:
    j       1b
    .size   basalt_start, . - basalt_start
