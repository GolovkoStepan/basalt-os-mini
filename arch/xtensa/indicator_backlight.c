// Индикатор жизни на T-Display-S3: подсветка экрана.
//
// Почему подсветка. На этой плате нет ни RGB-светодиода, ни свободного пина,
// который было бы не жалко: почти все GPIO заняты параллельной шиной экрана.
// Подсветка - единственное, что видно без терминала и при этом не портит
// картинку: включили - экран светится, выключили - тёмный.
//
// Чего здесь нет и почему:
//  - яркости. Вывод в 0 или 1: на плате стоит повышающий преобразователь
//    подсветки, и ШИМ на его разрешающем пине даёт не градации, а мерцание.
//    Числа r/g/b поэтому схлопываются в «есть цвет / нет цвета»;
//  - RMT. Передавать нечего, кадра нет - basalt_indicator_frame_us() = 0.
//
// Питание панели. На T-Display-S3 экран и подсветка питаются от отдельной
// линии PIN_POWER_ON (G15), которую надо поднять до включения подсветки.
// Забыть её - самый частый способ получить «прошивка работает, экран чёрный».

#include "indicator.h"

#include "board_pins.h"
#include "pin_gpio.h"
#include "tick.h"

// Готов ли драйвер. Нужен панике: до инициализации трогать пины нельзя, они
// ещё не переведены в GPIO, и запись уровня уйдёт в чужую функцию.
static bool ready;

const char* basalt_indicator_name(void)
{
    return "подсветка LCD на G38, питание панели на G15";
}

void basalt_indicator_init(void)
{
    // Сначала питание панели, потом подсветка: обратный порядок на части
    // ревизий платы даёт вспышку белым на долю секунды.
    pin_gpio_output(PIN_POWER_ON, true);
    pin_gpio_output(PIN_DISP_BL, false);

    // Пауза на подъём преобразователя. Стоит копейки, а без неё включение
    // подсветки сразу после питания может не сработать.
    basalt_delay_us(10000);

    ready = true;
}

void basalt_indicator_set(uint8_t r, uint8_t g, uint8_t b)
{
    // Сумма в uint32_t, а не в uint8_t: 255+255+255 переполнило бы байт.
    pin_gpio_write(PIN_DISP_BL, (uint32_t)r + g + b > 0);
}

bool basalt_indicator_memory_ok(void)
{
    // Проверять нечего: ошибка «кадры уходят в никуда» бывает только у
    // передатчика, у обычного пина такого режима отказа нет.
    return true;
}

bool basalt_indicator_ready(void)
{
    return ready;
}

uint32_t basalt_indicator_frame_us(void)
{
    return 0;
}
