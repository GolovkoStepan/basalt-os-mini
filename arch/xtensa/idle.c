// Ожидание до прерывания через `waiti`.
//
// ПРО ТАКТИРОВАНИЕ - главное, что здесь можно сделать неправильно.
//
// На ESP32-S3 в waiti можно погасить тактирование ядра: за это отвечает
// SYSTEM_CPU_WAIT_MODE_FORCE_ON в SYSTEM_CPU_PER_CONF_REG. IDF так и делает -
// при cpu_waiti_clk_gate=1 он БИТ ОЧИЩАЕТ, и тогда во время waiti ядро не
// тактируется.
//
// Нам это не подходит, и вот почему: тик у нас от CCOUNT, а CCOUNT считает
// такты ядра. Погасили тактирование - встал CCOUNT, а с ним и сравнение с
// CCOMPARE1. Прерывание не придёт никогда, и waiti уснёт навсегда. Это не
// гипотеза о поведении железа, а прямое следствие того, что CCOUNT - счётчик
// тактов ядра, а не отдельный от него таймер.
//
// Спасает то, что у бита сброс 1'b1 и IDF-шную инициализацию RTC мы не зовём.
// Но полагаться на состояние после сброса нельзя: загрузчик мог его тронуть.
// Поэтому ставим бит сами - явно и с объяснением.
//
// Цена: во время waiti ядро не экономит тактирование, и выигрыш только в том,
// что оно не выполняет инструкций (меньше шума, нет лишних обращений к
// памяти и шине). Настоящая экономия энергии - это отдельный сон с гашением
// тактирования и пробуждением от SYSTIMER; он появится, когда тик перестанет
// быть источником пробуждения.

#include "idle.h"

#include <stdint.h>

#include "soc/system_reg.h"
#include "soc/soc.h"

#include "tick.h"

// Счётчик засыпаний. Обычная переменная, не volatile: её читает и пишет один
// поток, а прерывание её не трогает.
static uint32_t s_waits;

void basalt_idle_init(void)
{
    // Явно: тактирование во время waiti не гасим (см. объяснение в шапке).
    SET_PERI_REG_MASK(SYSTEM_CPU_PER_CONF_REG, SYSTEM_CPU_WAIT_MODE_FORCE_ON);
}

uint32_t basalt_idle_waits(void)
{
    return s_waits;
}

void basalt_idle_wait(void)
{
    ++s_waits;

    // `waiti 2`, а не `waiti 0`: операнд - уровень PS.INTLEVEL, до которого
    // поднимается порог на время ожидания. У нас тик на уровне 3 и работает
    // при INTLEVEL = 2 (basalt_int1_init опускает порог на уровень ниже).
    // `waiti 2` будит прерывание ровно уровня 3 и выше - то есть тик, - а
    // уровни 1..2, которые у нас всё равно ведут в панику, остаются
    // замаскированными. `waiti 0` разрешил бы и их, а это значило бы, что
    // любое случайное прерывание от неиспользуемой периферии уводит систему
    // в панический обработчик.
    __asm__ volatile("waiti 2" ::: "memory");
}

void basalt_idle_until_us(uint64_t until_us)
{
    // Спим кусками до срока. Проверка в цикле обязательна: waiti возвращает
    // управление на ЛЮБОМ прерывании, а не только на тике, поэтому одно
    // ожидание может закончиться раньше срока.
    while (basalt_uptime_us() < until_us) {
        basalt_idle_wait();
    }
}

void basalt_idle_ms(uint32_t ms)
{
    basalt_idle_until_us(basalt_uptime_us() + (uint64_t)ms * 1000u);
}
