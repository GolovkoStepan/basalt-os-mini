// План выполнения командной строки: ступени конвейера и перенаправления.
//
// Зачем отдельный модуль, а не разбор прямо в шелле. Здесь принимаются
// решения, которые потом дорого переигрывать: что считается командой, куда
// идёт её вывод, можно ли в одной ступени дважды перенаправить одно и то же.
// Ошибка в этом месте выглядит не как «не собралось», а как «`echo a > f`
// молча напечатал на экран» - то есть её ищут глазами по логу. Поэтому
// решает чистая функция, а проверяется она на маке (`test_redirect`), где
// `echo a > f` стоит одну строку.
//
// Что здесь есть: `>`, `>>`, `<` и `|`. Чего нет: `;`, `&&`, `2>`, `$` и `*` -
// им нужны разделение команд, отдельный поток ошибок или окружение, и это
// отдельные решения (см. parse.h).
//
// Почему ступеней фиксированное число. Конвейер у нас без процессов: ступени
// выполняются по очереди, вывод предыдущей копится в буфере. Бесконечная
// цепочка в такой схеме означала бы бесконечный буфер, поэтому предел
// объявлен честно, а не «сколько влезет».

#pragma once

#include <stdbool.h>

#include "parse.h"

// Сколько ступеней конвейера принимаем. Четыре - это три `|`; больше на
// терминале 53x17 всё равно не прочитать.
#define REDIRECT_MAX_STAGES 3

typedef struct {
    int argc;
    char** argv;         // указывает внутрь parse_result; годится, пока жива строка
    const char* out_path;  // NULL - вывод на экран (или в конвейер)
    bool append;           // true для `>>`
    const char* in_path;   // NULL - ввода нет
} redirect_stage;

typedef struct {
    int count;
    redirect_stage stage[REDIRECT_MAX_STAGES];
} redirect_plan;

typedef enum {
    REDIRECT_OK = 0,

    // Ступень без команды: `| ls`, `ls |`, `ls | | wc`, а также строка из
    // одних перенаправлений (`> f`). Выполнять нечего, а молча проглотить -
    // значит показать пустоту вместо ошибки.
    REDIRECT_ERR_NO_COMMAND,

    // `echo a >` без имени файла: непонятно, куда писать.
    REDIRECT_ERR_NO_TARGET,

    // Два `>` (или два `<`) в одной ступени. В sh побеждает последний, и
    // первый файл создаётся пустым - это ровно тот случай, когда «как в sh»
    // хуже, чем честная ошибка.
    REDIRECT_ERR_DOUBLE_OUT,
    REDIRECT_ERR_DOUBLE_IN,

    REDIRECT_ERR_STAGES,
} redirect_status;

// Построить план. Меняет parse_result: слова одной ступени сдвигаются в
// начало массива argv, чтобы ступень была непрерывным куском.
redirect_status redirect_build(parse_result* parsed, redirect_plan* out);

// Текст ошибки по-русски.
const char* redirect_strerror(redirect_status st);
