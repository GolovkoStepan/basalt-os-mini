// Разбор командной строки на слова.
//
// Зачем отдельный модуль, а не strtok в шелле. У командной строки есть свои
// правила (кавычки, экранирование, комментарий), и именно в них живут ошибки:
// `echo "a b"` должен быть одним словом, а `echo a\ b` - тоже одним. Проверять
// это на плате, набирая вслепую в терминале, - худший из способов; здесь же
// это десяток строк теста на маке.
//
// Разбор идёт **в самом буфере**, без выделения памяти: слова разделяются
// нулями, argv указывает внутрь строки. Куча на A3 есть, но команда, которая
// падает от нехватки памяти при разборе собственных аргументов, - это плохая
// команда. Цена решения: строка должна быть изменяемой и жить, пока жив argv.
//
// Чего здесь нет и почему. Перенаправлений, конвейеров и `;` нет: им нужны
// файловые дескрипторы и процессы, а их не будет до A9/A10. Подстановки `$` и
// `*` нет по той же причине - их нельзя делать, не зная окружения и файлов.

#pragma once

#include <stddef.h>

// Сколько слов принимаем. Больше десяти не нужно ни одной нашей команде, а
// массив фиксированного размера избавляет от malloc и от вопроса «что делать,
// когда он не удался».
#define PARSE_MAX_ARGS 16

typedef enum {
    PARSE_OK = 0,

    // Кавычка не закрыта до конца строки. Это не «мелочь, доделаем сами»:
    // угадывание сделало бы `echo "a b` неотличимым от `echo "a b"`, и
    // ошибку в кавычках стало бы видно только по неверному выводу.
    PARSE_ERR_QUOTE,

    // Слов больше, чем PARSE_MAX_ARGS. Обрезать молча нельзя: команда
    // выполнилась бы не с теми аргументами, которые набраны.
    PARSE_ERR_ARGS,
} parse_status;

typedef struct {
    int argc;
    char* argv[PARSE_MAX_ARGS];
} parse_result;

// Разобрать строку. Меняет её: расставляет нули на месте разделителей.
//
// Правила:
//   * разделитель - пробел или табуляция, несколько подряд считаются одним;
//   * `'...'` - всё буквально, обратной косой черты внутри нет;
//   * `"..."` - обратная косая черта экранирует только `"` и `\`, как в sh;
//   * `\` вне кавычек экранирует следующий символ, включая пробел;
//   * `#` в начале слова - комментарий до конца строки;
//   * пустые кавычки дают пустое слово: `echo ""` печатает пустую строку, а
//     не ничего.
//
// При ошибке содержимое out не определено - вызывающему незачем его смотреть.
parse_status parse_line(char* line, parse_result* out);
