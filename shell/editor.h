// Полноэкранный редактор текста: буфер, курсор, клавиши, окно.
//
// Зачем отдельный модуль. В редакторе две части: что записано в файле и как
// это показано. «Что записано» - это байты, курсор и клавиши: вставка, стирание,
// склейка строк, поиск, предел ёмкости. Ошибка здесь видна не как «не
// собралось», а как «после Enter пропала строка» или «кириллица стёрлась по
// половине» - и искать её пришлось бы на 53-колоночном экране платы. Поэтому
// текст и клавиши живут здесь и проверяются на маке (`test_editor`), а
// `src/shell/main.c` остаётся связкой с матрицей, USB и VFS.
//
// Модуль ничего не знает ни про экран, ни про файлы: буфер ему даёт
// вызывающий, а сохранение делает вызывающий по событию ED_SAVE. Так же
// устроены `pager` и `xmodem`.
//
// Текст хранится одним куском UTF-8 с переводами строк, а не массивом строк.
// Файл на 64 КБ с массивом строк потребовал бы индекса на несколько тысяч
// записей и отдельного решения, что делать при вставке. Один буфер и проход
// по нему - цена в лишний проход на каждое нажатие, зато нет второго источника
// истины, который однажды разойдётся с текстом.
//
// Курсор - смещение в байтах. Наружу отдаются клетки: «Ж» занимает два байта
// и одну клетку, и путать эти величины нельзя (то же правило, что в lineedit).

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "utf8.h"

// Клеток в строке и строк под текст. 53x16 - это экран 53x17 минус нижняя
// строка состояния. Числа совпадают с TEXT_COLS/TEXT_ROWS намеренно: окно
// редактора и экран - одно и то же.
#define EDITOR_COLS 53
#define EDITOR_ROWS 16

// Ширина табуляции. Восемь - как в матрице и в `less`: иначе один и тот же
// файл в редакторе, в `cat` и в `less` выглядел бы по-разному.
#define EDITOR_TAB 8

typedef enum {
    // Ничего не изменилось: служебный байт, продолжение UTF-8 или
    // escape-последовательности, клавиша, которой мы не знаем.
    ED_NONE = 0,

    // Текст или позиция курсора изменились - надо перерисовать.
    ED_CHANGED,

    // Ctrl-S: сохранить. Пишет вызывающий: модуль не знает ни VFS, ни имени
    // файла, а значит, не может и соврать про то, что «сохранено».
    ED_SAVE,

    // Ctrl-Q/Ctrl-C, несохранённого нет: можно выходить.
    ED_QUIT,

    // Ctrl-Q/Ctrl-C, есть несохранённое: первый раз просим подтверждение,
    // второй - выходим. Молча терять набранное нельзя, а отдельного диалога
    // с кнопками на этом экране нет.
    ED_QUIT_DIRTY,

    // Ctrl-F: вызывающий спрашивает строку и зовёт ed_search.
    ED_FIND,

    // Действие невозможно: стирать нечего, буфер полон.
    ED_BELL,
} ed_event;

typedef struct {
    // Буфер и его ёмкость в байтах. Принадлежит вызывающему: редактор не
    // выделяет память и не знает, PSRAM это или стек в тесте.
    char* buf;
    uint32_t cap;
    uint32_t len;

    uint32_t cursor;   // смещение курсора в байтах
    uint32_t top;      // смещение начала верхней строки окна
    uint32_t left;     // прокрутка по горизонтали, в клетках
    uint32_t goal;     // желаемая колонка для стрелок вверх/вниз, в клетках

    bool dirty;        // были правки после загрузки или сохранения
    bool quit_armed;   // первый Ctrl-Q на несохранённом уже был

    int esc;           // состояние разбора escape-последовательности
    int esc_num;       // накопленное число в ESC [ <число> ~
    utf8_decoder dec;
} editor;

// Отдать буфер и сбросить состояние: пустой текст, курсор в начале.
void ed_init(editor* ed, char* buf, uint32_t cap);

// Загрузить len байт, которые уже лежат в buf. Разбор идёт на месте, поэтому
// второго буфера на 64 КБ не нужно. Что делается с содержимым:
//   - BOM в начале выбрасывается: залитые с мака файлы иногда с ним, а
//     показывать его как «?» в первой клетке незачем;
//   - CRLF превращается в LF: иначе каждая строка заканчивалась бы лишним
//     символом, и курсор в конце строки стоял бы не там, где ждёт человек.
// После загрузки текст считается несохранённым только если его правда
// изменили: открыть файл и сразу выйти - это не правка.
void ed_load(editor* ed, uint32_t len);

const char* ed_data(const editor* ed);
uint32_t ed_len(const editor* ed);
bool ed_dirty(const editor* ed);

// Вызывается после успешной записи файла: снимает флаг правок и взведённое
// подтверждение выхода.
void ed_mark_saved(editor* ed);

// Скормить один принятый из консоли байт. Клавиши разбираются здесь же:
// стрелки и Delete приходят escape-последовательностями, кириллица - UTF-8.
ed_event ed_input(editor* ed, uint8_t byte);

// Найти подстроку, начиная со следующего символа после курсора, с переходом
// в начало файла. 0 - нашли (курсор встал на совпадение), -1 - нет.
// Поиск побайтовый: UTF-8 устроен так, что совпадение подстроки не может
// начаться с середины символа, если искомая строка набрана целиком.
int ed_search(editor* ed, const char* needle);

// Строка окна (0..EDITOR_ROWS-1) в клетках. Возвращает число заполненных
// клеток; остальные вызывающий гасит пробелами. Строки за концом файла дают 0.
int ed_row(const editor* ed, int row, uint16_t* cells, int cap);

// Где курсор на экране: строка окна и колонка после горизонтальной прокрутки.
void ed_cursor_screen(const editor* ed, int* row, int* col);

// Номер строки и колонки курсора для строки состояния, с единицы.
void ed_line_col(const editor* ed, uint32_t* line, uint32_t* col);
