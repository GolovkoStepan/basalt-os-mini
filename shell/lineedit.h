// Редактор строки: буфер с курсором внутри, история, управляющие клавиши.
//
// Зачем свой, а не канонический режим tty. В каноне терминал умеет ровно две
// вещи: дописать символ в конец и стереть последний. Этого хватает, чтобы
// набрать команду, но не хватает, чтобы её исправить: стрелки, Ctrl-A/E,
// вырезание хвоста и история требуют курсора внутри строки, а не только на её
// конце. Так же устроены настоящие терминалы: программа переводит tty в raw и
// редактирует строку сама. Здесь то же самое, и поэтому tty/tty.c не пришлось
// усложнять - он по-прежнему про байты, а не про клавиши.
//
// Модуль не знает ни про экран, ни про USB: он принимает code point и отдаёт
// событие «перерисовать», «строка готова», «нечего стирать». Что нарисовать и
// где стоит курсор - знает вызывающий, поэтому набор текста проверяется на
// маке без платы.
//
// Курсор считается в байтах (так проще резать буфер), а наружу отдаётся ещё и
// в клетках экрана: кириллица занимает две единицы в буфере и одну на экране,
// и путать эти две величины нельзя.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Предел строки. Совпадает с HISTORY_LINE_CAP: строка, влезшая сюда, влезает
// и в историю, и обрезать её не приходится.
#define LINEEDIT_CAP 256

typedef enum {
    // Ничего не изменилось: служебный байт, продолжение escape-последовательности
    // или клавиша, которой мы не знаем.
    LE_NONE = 0,

    // Строка или позиция курсора изменились - надо перерисовать.
    LE_CHANGED,

    // Enter: строка готова, она уже записана в историю.
    LE_SUBMIT,

    // Ctrl-C: набранное выброшено, начинаем заново.
    LE_INTR,

    // Ctrl-D на пустой строке: конец ввода.
    LE_EOF,

    // Действие невозможно: стирать нечего, курсор в начале, строка полна.
    LE_BELL,

    // Ctrl-L: перерисовать экран. Отдельное событие, а не LE_CHANGED: чистить
    // экран - дело вызывающего, а «строка изменилась» и «покажи всё заново» -
    // разные вещи, и склеивать их значило бы заставить редактор знать про
    // очистку.
    LE_REDRAW,
} le_event;

void le_init(void);

// Начать новую пустую строку. Вызывается после LE_SUBMIT, LE_INTR и LE_EOF,
// а не автоматически: до этого вызывающий ещё читает le_line().
void le_reset(void);

// Положить готовый текст и поставить курсор в конец. Нужно тестам и подсказкам
// (например, «повторить последнюю команду»).
void le_set_line(const char* text);

// Скормить один принятый символ.
le_event le_input(uint32_t cp);

const char* le_line(void);
size_t le_len(void);

// Позиция курсора в байтах буфера - для разрезания и вставки.
size_t le_cursor(void);

// Ширина строки и позиция курсора в клетках экрана. Отдельно от байтов:
// «Ж» - это два байта и одна клетка, и рисовать надо по клеткам.
size_t le_cols(void);
size_t le_cursor_col(void);

// Code point в клетке index (0 - первый символ строки) или 0, если клетки нет.
// Рисующему нужен именно этот доступ: ходить по байтам он не может - разрез
// попал бы в середину двухбайтовой буквы.
uint32_t le_cell_cp(size_t index);
