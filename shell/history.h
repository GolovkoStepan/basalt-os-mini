// История команд: кольцо из последних строк.
//
// Зачем отдельный модуль, а не массив внутри редактора строки. История - это
// данные со своей жизнью: у неё есть политика (что хранить, что выбрасывать),
// и проверять её хочется отдельно от разбора нажатий. Редактор спрашивает
// «дай предыдущую», а как она хранится, его не касается.
//
// Ноль - это не команда, а пустая строка. Пустые строки и повтор последней не
// хранятся: Enter без текста и «листать историю» одинаково часты, и без этого
// кольцо заполнялось бы копиями одной и той же команды, вытесняя полезное.

#pragma once

#include <stdbool.h>
#include <stddef.h>

// Сколько команд помним. Восьми хватает, чтобы вернуться к тому, что набирали
// минуту назад, и при этом кольцо занимает 2 КБ SRAM - их не жалко, но и
// растягивать до сотни незачем: экран всё равно не покажет больше.
#define HISTORY_CAP 8

// Предел одной записи. Совпадает с буфером редактора строки (LINEEDIT_CAP):
// если строка влезла в редактор, она влезет и сюда, и обрезать её не придётся.
#define HISTORY_LINE_CAP 256

void history_init(void);

// Запомнить строку. Возвращает false, если она не поместилась в запись или
// если запоминать её не стали (пустая, повтор последней). Вызывающему это
// знать не обязательно, но тесту - нужно.
bool history_push(const char* line);

// Сколько записей сейчас. Меньше HISTORY_CAP, пока кольцо не заполнилось.
int history_count(void);

// Запись по номеру: 0 - самая старая из хранимых, count-1 - последняя.
// Возвращает пустую строку за пределами диапазона, а не NULL: вызывающему
// тогда не нужно проверять указатель на каждом шаге листания.
const char* history_get(int index);

void history_clear(void);
