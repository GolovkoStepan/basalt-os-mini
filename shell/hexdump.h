// Форматирование строки hex-дампа.
//
// Зачем отдельный модуль, а не печать прямо в команде. Строка дампа - это
// арифметика: смещение, выравнивание неполной строки, колонка ASCII. Ошибка
// в ней выглядит не как «не собралось», а как «колонки разъехались на строках
// длиной не кратной восьми», и искать её пришлось бы глазами по экрану платы.
// Здесь она стоит одного теста на маке (`test_hexdump`).
//
// Почему 8 байт в строке, а не 16, как в `hexdump -C`. Экран платы - 53
// колонки, а строка из 16 байт занимает 78: она переносится, и таблица
// рассыпается ровно там, где нужна. Восемь байт дают 45 колонок - влезает
// вместе с приглашением, если вывод идёт в файл или через конвейер, ширина
// та же, но это уже дело читающего.
//
// Модуль не знает ни про ФС, ни про экран: на вход байты, на выход строка.

#pragma once

#include <stddef.h>
#include <stdint.h>

// Байт данных в строке. Меняя, помните про ширину экрана (см. выше).
#define HEXDUMP_BYTES 8

// Сколько места нужно под строку, включая '\n' и ноль.
// 8 (смещение) + 2 + 8*3-1 (hex с пробелами) + 2 + 1 + 8 (ASCII) + 1 + '\n' + '\0'
#define HEXDUMP_LINE_MAX 48

// Собрать одну строку дампа:
//
//   00000000  48 65 6c 6c 6f 2c 20 77  |Hello, w|
//
// offset - смещение первого байта строки, len - сколько байт в data (0..8).
// Неполная строка дополняется пробелами в hex-колонке, чтобы ASCII всегда
// начиналась с одной и той же колонки: иначе последняя строка файла прыгает.
//
// Возвращает длину строки без нуля. Если cap меньше HEXDUMP_LINE_MAX,
// возвращает 0 и ничего не пишет: обрезанная строка дампа хуже пустой,
// потому что её легко принять за настоящие данные.
size_t hexdump_line(char* out, size_t cap, uint32_t offset,
                    const uint8_t* data, size_t len);
