// Приём файла по XMODEM: пакеты, CRC, подтверждение на каждый пакет.
//
// Зачем свой приёмник. Файл на плату нужно положить без Wi-Fi, без SD и без
// снятия flash - единственный канал, который всегда под рукой, это консоль, он
// же USB Serial/JTAG. XMODEM - самый простой протокол, который переживает
// потерю и порчу байтов: пакет с номером, CRC и ACK/NAK на каждый пакет.
// Ни имени файла, ни прав он не передаёт - это и не нужно: имя задаёт команда
// на плате, а правам взяться неоткуда.
//
// Модуль переносимый: ни регистров, ни консоли, ни ФС. Всё, что ему нужно от
// мира, - три функции в xmodem_io, поэтому он проверяется на маке
// (test/test_xmodem), а на плате те же три функции - это консоль, таймер и
// VFS. Так же устроены tty и parse: решение проверяется без платы, плата
// остаётся только проводом.
//
// Что здесь есть и чего нет. Есть приём (xmodem_receive) - отправку с мака
// делает tools/xsend.py, и ей довольно питона, чтобы не тащить второй модуль
// в прошивку. Нет YMODEM (имени файла в первом пакете) и нет режима 8 КБ:
// файлы сюда приходят настройками и образами в десятки-сотни килобайт, а
// 1 КБ на пакет уже даёт проценты накладных расходов, а не десятки.

#pragma once

#include <stddef.h>
#include <stdint.h>

// Коды возврата. Ноль - успех, остальное отрицательное: `if (rc)` читается
// без сравнения с нулём.
enum {
    XMODEM_OK = 0,
    XMODEM_ERR_ARG = -1,       // нет колбэка или io
    XMODEM_ERR_IO = -2,        // не удалось ни прочитать, ни подтвердить
    XMODEM_ERR_TIMEOUT = -3,   // отправитель не начал или замолчал
    XMODEM_ERR_PROTOCOL = -4,  // пакеты приходят битыми слишком долго
    XMODEM_ERR_SEQUENCE = -5,  // номер пакета не тот: поток разъехался
    XMODEM_ERR_CANCEL = -6,    // отправитель прислал CAN CAN
    XMODEM_ERR_SINK = -7,      // приёмник данных отказался писать
};

// Откуда и куда идут байты. ctx - что угодно вызывающего, колбэки его не
// трогают.
typedef struct {
    void* ctx;

    // Записать ровно len байт в линию. Возвращает сколько записано.
    int (*put)(void* ctx, const uint8_t* data, size_t len);

    // Прочитать до len байт, ожидая не дольше timeout_ms на весь вызов.
    // Возвращает сколько пришло; меньше len - срок истёк (это не ошибка, а
    // повод повторить или ответить NAK). timeout_ms = 0 - только то, что уже
    // лежит в буфере.
    int (*get)(void* ctx, uint8_t* data, size_t len, uint32_t timeout_ms);

    // Принять очередной кусок файла. 0 - дальше, любое другое - отказ
    // (например, кончилось место), передача прекращается.
    int (*sink)(void* ctx, const uint8_t* data, size_t len);

    // Данные кончились: дописать всё, что придержано внутри приёмника (у
    // оболочки это буфер записи во flash). Зовётся до ACK на EOT, поэтому
    // отправитель узнаёт об успехе только после того, как файл действительно
    // записан. Иначе ACK означал бы «принял в память», и сброс платы сразу
    // после передачи мог бы оставить пустой файл при честном ответе.
    // 0 - записано, любое другое - отказ (XMODEM_ERR_SINK).
    int (*finish)(void* ctx);
} xmodem_io;

// Принять один файл. В *size кладётся число байт, отданных sink: хвостовое
// дополнение последнего пакета (0x1A) отбрасывается, потому что это не данные
// файла, а заполнитель XMODEM.
//
// Вызов один за раз: буферы пакета и хвоста статические, чтобы не тратить
// несколько килобайт стека оболочки. Планировщика в системе нет, так что
// «один за раз» здесь не ограничение, а свойство.
int xmodem_receive(const xmodem_io* io, uint32_t* size);

// Текст ошибки по-русски - для оболочки.
const char* xmodem_strerror(int rc);
