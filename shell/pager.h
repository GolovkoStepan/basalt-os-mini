// Разметка страницы: строки экрана из байтов потока.
//
// Зачем отдельный модуль. В `less` две части: что показать и как листать.
// «Что показать» - это арифметика над байтами: перенос длинной строки на
// следующую строку экрана, табуляция по клеткам, CRLF из файлов, залитых с
// мака, символ UTF-8, разрезанный границей чтения. Ошибка здесь выглядит не
// как «не собралось», а как «на тринадцатой странице пропала строка», и искать
// её пришлось бы глазами по экрану платы. Поэтому разметка живёт здесь и
// проверяется на маке (`test_pager`), а команда в шелле остаётся про клавиши и
// экран.
//
// Модуль ничего не знает ни про ФС, ни про матрицу: на вход байты через
// колбэки, на выход клетки по code point. Так же устроен приёмник XMODEM.
//
// Почему страница целиком, а не «печатать, пока влезает». Печать сразу в
// матрицу не оставляет пути назад: если строка не влезла в остаток страницы,
// её начало уже нарисовано, и вернуться к предыдущей странице нечем. Страница
// собирается в клетках и рисуется одной операцией, поэтому назад можно
// вернуться, перечитав поток с сохранённого смещения.
//
// Перенос строки - ленивый: строка экрана обрывается не в момент, когда
// набралось 53 клетки, а когда понадобилось положить 54-ю. Отсюда следует, что
// перевод строки на границе страницы не даёт пустой строки, и отдельного
// состояния «первая строка - продолжение» не нужно: смещение следующей
// страницы указывает ровно на первый непоказанный байт.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

#include "utf8.h"

// Клеток в строке и строк на странице. 53x16 - это экран 53x17 минус нижняя
// строка состояния. Числа совпадают с TEXT_COLS/TEXT_ROWS намеренно: страница
// и экран - одно и то же, и расхождение видно как «последняя строка страницы
// уехала под состояние».
#define PAGER_COLS 53
#define PAGER_ROWS 16

// Сколько байт потока держим в буфере. Меньше сектора BFS (4 КБ) намеренно:
// страница - шестнадцать строк по 53 клетки, и держать под неё целый сектор
// незачем. Но и двух байт мало: UTF-8 требует до трёх продолжений подряд.
#define PAGER_CHUNK 512

// Откуда читать. Колбэки, а не файл: у `less` источник бывает трёх видов -
// имя файла, `< файл` и конвейер, а у конвейера нет ни дескриптора, ни
// возможности вернуться назад.
typedef struct {
    void* ctx;
    // Прочитать до cap байт. 0 - успех, в том числе *got == 0 на конце
    // потока; отрицательный код - ошибка.
    int (*read)(void* ctx, uint8_t* dst, uint32_t cap, uint32_t* got);
    // Встать на абсолютное смещение. NULL - поток не прокручиваем.
    int (*seek)(void* ctx, uint32_t offset);
} pager_io;

typedef struct {
    pager_io io;
    uint8_t buf[PAGER_CHUNK];
    uint32_t len;    // сколько байт в буфере
    uint32_t pos;    // сколько из них уже разобрано
    uint32_t base;   // абсолютное смещение buf[0]
    bool eof;
    int error;
    utf8_decoder dec;
} pager;

typedef struct {
    int rows;       // сколько строк показывать; 0 - поток кончился
    bool eof;       // поток кончился, следующей страницы нет
    uint32_t next;  // смещение первого непоказанного байта
} pager_page;

void pager_init(pager* p, pager_io io);

// Перечитать поток с offset. Нужно для возврата на предыдущую страницу:
// у файла есть seek, у конвейера нет - тогда вернётся -1, и вызывающий
// честно скажет, что назад нельзя.
int pager_seek(pager* p, uint32_t offset);

// Собрать страницу. Клетки, которых не хватило, остаются нулями - вызывающий
// рисует строку до первого нуля.
pager_page pager_fill(pager* p, uint16_t (*cells)[PAGER_COLS]);
