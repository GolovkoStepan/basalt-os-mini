// Приёмник консоли для тестов текста.
//
// Зачем он вообще нужен: в сборку тестов попадает весь build_src_filter, то
// есть и format.c, который нужен соседнему набору (test_format). format.c
// линкуется с basalt_console_write, а её на хосте даёт заглушка того набора -
// сюда она не видна. Без этой функции набор не собирается, хотя ни один тест
// текста в консоль не пишет.
//
// Поэтому здесь не буфер, а приёмник: текст пишется в никуда. Если однажды
// понадобится проверять в тексте и консольный вывод, это станет копией
// test_format/console_stub.c - и тогда заглушку надо будет вынести в общее
// место, а не заводить третью копию.

#include <stddef.h>

#include "console_usb_jtag.h"

size_t basalt_console_write(const void* data, size_t len)
{
    (void)data;
    return len;
}
