#!/usr/bin/env python3
"""Генератор шрифта 5x7 для текстового режима.

Зачем свой генератор, а не готовый шрифт из библиотеки:
  - глифы видно прямо здесь, в исходнике, и можно поправить форму одной
    строкой. В упакованном виде (#define, 7 байт на букву) форму не увидеть;
  - генератор проверяет геометрию: глиф ровно 5 на 7 и только из двух
    символов. Опечатка в ширине иначе превратилась бы в сдвинутый текст на
    экране - искать такое в готовом шрифте почти невозможно;
  - шрифт пиксельный, а не рендер TrueType. На 7 px высоты TrueType с
    хинтингом даёт кашу, и форму всё равно пришлось бы рисовать руками.

Запуск (плата и Pillow не нужны, только python3):

    python3 tools/make_font.py              # перезаписать text/font_5x7.h
    python3 tools/make_font.py --preview    # напечатать шрифт в терминал

--preview печатает весь набор таблицей: глазами видно, что буквы вышли
буквами. Это единственная проверка формы, которая есть, - поэтому она и
встроена в генератор, а не оставлена на «посмотреть на плате».

Формат заголовка: 7 байт на глиф, по байту на строку, старшие биты значат
левые пиксели (0x10 - самый левый столбец, 0x01 - самый правый).
"""

