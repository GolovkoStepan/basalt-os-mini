OUT = Path(__file__).resolve().parent.parent / "text" / "font_5x7.h"


def check() -> None:
    """Проверить геометрию до генерации.

    Ошибка здесь дешевле ошибки на экране: сдвинутый глиф выглядит как «шрифт
    поехал», и искать причину начинают в рендерере, а не в данных.
    """
    expected = {chr(c) for c in range(FIRST_CODE, LAST_CODE + 1)}
    missing = sorted(expected - set(GLYPHS))
    extra = sorted(set(GLYPHS) - expected)
    if missing:
        sys.exit(f"нет глифов: {' '.join(repr(c) for c in missing)}")
    if extra:
        sys.exit(f"лишние глифы вне 0x20..0x7E: {' '.join(repr(c) for c in extra)}")

    for ch, rows in GLYPHS.items():
        if len(rows) != GLYPH_H:
            sys.exit(f"{ch!r}: строк {len(rows)}, нужно {GLYPH_H}")
        for i, row in enumerate(rows):
            if len(row) != GLYPH_W:
                sys.exit(f"{ch!r}, строка {i}: ширина {len(row)}, нужно {GLYPH_W}")
            bad = set(row) - {"#", "."}
            if bad:
                sys.exit(f"{ch!r}, строка {i}: посторонние символы {sorted(bad)}")


def pack(rows) -> list:
    """Строки ASCII-арта в байты: 0x10 - левый пиксель, 0x01 - правый."""
    out = []
    for row in rows:
        value = 0
        for x, pixel in enumerate(row):
            if pixel == "#":
                value |= 0x10 >> x
        out.append(value)
    return out


def preview() -> None:
    chars = [chr(c) for c in range(FIRST_CODE, LAST_CODE + 1)]
    band = 16
    for start in range(0, len(chars), band):
        chunk = chars[start:start + band]
        print("  ".join(f"{c!r:>4}" for c in chunk))
        for line in range(GLYPH_H):
            cells = []
            for c in chunk:
                cells.append(GLYPHS[c][line].replace(".", " ").replace("#", "#"))
            print("  ".join(f" {cell} " for cell in cells).rstrip())
        print()


def main() -> None:
    check()

    if "--preview" in sys.argv:
        preview()
        return

    lines = []
    add = lines.append

    add("// Сгенерировано tools/make_font.py - НЕ ПРАВИТЬ ВРУЧНУЮ.")
    add("// Шрифт 5x7, коды 0x20..0x7E: 7 байт на глиф, по байту на строку.")
    add("// Старший бит строки (0x10) - левый пиксель, 0x01 - правый.")
    add("//")
    add("// Менять форму буквы - в генераторе, здесь только результат.")
    add("")
    add("#pragma once")
    add("")
    add("#include <stdint.h>")
    add("")
    add(f"#define FONT_GLYPH_W     {GLYPH_W}")
    add(f"#define FONT_GLYPH_H     {GLYPH_H}")
    add(f"#define FONT_FIRST_CODE  0x{FIRST_CODE:02X}")
    add(f"#define FONT_GLYPH_COUNT {len(GLYPHS)}")
    add("")
    add("static const uint8_t kFont5x7[FONT_GLYPH_COUNT][FONT_GLYPH_H] = {")
    for code in range(FIRST_CODE, LAST_CODE + 1):
        ch = chr(code)
        values = pack(GLYPHS[ch])
        body = ", ".join(f"0x{v:02X}" for v in values)
        # repr, а не сам символ: глиф обратной косой черты (0x5C) в конце
        # комментария склеивает строку со следующей, и GCC справедливо ругается
        # «multi-line comment». В кавычках такой символ безвреден.
        add(f"    {{{body}}},  // 0x{code:02X} {ch!r}")
    add("};")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = len(GLYPHS) * GLYPH_H
    print(f"{len(GLYPHS)} глифов, {GLYPH_W}x{GLYPH_H}, {total} Б данных")
    print(f"готово: {OUT}")


if __name__ == "__main__":
    main()
