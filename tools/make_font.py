CYR_FIRST = 0x410
CYR_LAST = 0x44F
YO_UPPER = 0x401
YO_LOWER = 0x451

OUT_DIR = Path(__file__).resolve().parent.parent / "text"
OUT_H = OUT_DIR / "font_5x7.h"
OUT_C = OUT_DIR / "font_5x7.c"


def check_set(name: str, glyphs: dict, expected: set) -> None:
    """Проверить, что набор глифов ровно тот, что обещан, и верной формы.

    Ошибка здесь дешевле ошибки на экране: сдвинутый глиф выглядит как «шрифт
    поехал», и искать причину начинают в рендерере, а не в данных.
    """
    missing = sorted(expected - set(glyphs))
    extra = sorted(set(glyphs) - expected)
    if missing:
        sys.exit(f"{name}: нет глифов: {' '.join(repr(c) for c in missing)}")
    if extra:
        sys.exit(f"{name}: лишние глифы: {' '.join(repr(c) for c in extra)}")

    for ch, rows in glyphs.items():
        if len(rows) != GLYPH_H:
            sys.exit(f"{ch!r}: строк {len(rows)}, нужно {GLYPH_H}")
        for i, row in enumerate(rows):
            if len(row) != GLYPH_W:
                sys.exit(f"{ch!r}, строка {i}: ширина {len(row)}, нужно {GLYPH_W}")
            bad = set(row) - {"#", "."}
            if bad:
                sys.exit(f"{ch!r}, строка {i}: посторонние символы {sorted(bad)}")
        # Пустой глиф - почти всегда признак опечатки: набрали «.....» вместо
        # «#####». Пробел пуст законно, остальные буквы - нет.
        if ch != " " and not any("#" in row for row in rows):
            sys.exit(f"{ch!r}: глиф пуст целиком - опечатка в строках")


def check() -> None:
    check_set("ASCII", GLYPHS, {chr(c) for c in range(FIRST_CODE, LAST_CODE + 1)})
    check_set("кириллица", CYR_GLYPHS, {chr(c) for c in range(CYR_FIRST, CYR_LAST + 1)})
    check_set("Ё/ё", YO_GLYPHS, {chr(YO_UPPER), chr(YO_LOWER)})


def pack(rows) -> list:
    """Строки ASCII-арта в байты: 0x10 - левый пиксель, 0x01 - правый."""
    out = []
    for row in rows:
        value = 0
        for x, pixel in enumerate(row):
            if pixel == "#":
                value |= 0x10 >> x
        out.append(value)
    return out


def preview() -> None:
    # Один словарь на просмотр: так preview не знает, в какой из трёх таблиц
    # лежит буква, - а знать ему незачем.
    all_glyphs = {**GLYPHS, **CYR_GLYPHS, **YO_GLYPHS}

    blocks = [
        ("ASCII 0x20..0x7E",
         [chr(c) for c in range(FIRST_CODE, LAST_CODE + 1)]),
        ("кириллица 0x410..0x44F",
         [chr(c) for c in range(CYR_FIRST, CYR_LAST + 1)]),
        ("Ё и ё", [chr(YO_UPPER), chr(YO_LOWER)]),
    ]
    band = 16
    for title, chars in blocks:
        print(f"--- {title}")
        for start in range(0, len(chars), band):
            chunk = chars[start:start + band]
            print("  ".join(f"{c:>4}" for c in chunk))
            for line in range(GLYPH_H):
                cells = [all_glyphs[c][line] for c in chunk]
                print("  ".join(f" {cell.replace('.', ' ')} " for cell in cells).rstrip())
            print()


def emit_table(add, name: str, glyphs: dict, codes: list) -> None:
    """Один массив: [len(codes)][FONT_GLYPH_H] плюс комментарий с символом."""
    add(f"static const uint8_t {name}[{len(codes)}][FONT_GLYPH_H] = {{")
    for code in codes:
        ch = chr(code)
        rows = glyphs[ch]
        body = ", ".join(f"0x{v:02X}" for v in pack(rows))
        # repr, а не сам символ: глиф обратной косой черты (0x5C) в конце
        # комментария склеивает строку со следующей, и GCC справедливо ругается
        # «multi-line comment». В кавычках такой символ безвреден.
        add(f"    {{{body}}},  // 0x{code:04X} {ch!r}")
    add("};")
    add("")


def main() -> None:
    check()

    if "--preview" in sys.argv:
        preview()
        return

    ascii_codes = list(range(FIRST_CODE, LAST_CODE + 1))
    cyr_codes = list(range(CYR_FIRST, CYR_LAST + 1))
    total = len(GLYPHS) + len(CYR_GLYPHS) + len(YO_GLYPHS)

    # --- заголовок -------------------------------------------------------
    h = []
    add = h.append

    add("// Сгенерировано tools/make_font.py - НЕ ПРАВИТЬ ВРУЧНУЮ.")
    add("// Шрифт 5x7: ASCII 0x20..0x7E, кириллица 0x410..0x44F, плюс Ё и ё.")
    add("// 7 байт на глиф, по байту на строку.")
    add("// Старший бит строки (0x10) - левый пиксель, 0x01 - правый.")
    add("//")
    add("// Менять форму буквы - в генераторе, здесь только результат.")
    add("")
    add("#pragma once")
    add("")
    add("#include <stdint.h>")
    add("")
    add(f"#define FONT_GLYPH_W     {GLYPH_W}")
    add(f"#define FONT_GLYPH_H     {GLYPH_H}")
    add(f"#define FONT_ASCII_FIRST 0x{FIRST_CODE:02X}")
    add(f"#define FONT_ASCII_LAST  0x{LAST_CODE:02X}")
    add(f"#define FONT_CYR_FIRST   0x{CYR_FIRST:04X}")
    add(f"#define FONT_CYR_LAST    0x{CYR_LAST:04X}")
    add(f"#define FONT_GLYPH_COUNT {total}")
    add("")
    add("// Глиф по коду символа или NULL, если такого глифа нет.")
    add("//")
    add("// Возвращается указатель на FONT_GLYPH_H байт, а не копия: таблицы в")
    add("// font_5x7.c и живут во flash, копировать их в стек незачем.")
    add("const uint8_t* font_glyph(uint32_t cp);")
    add("")

    # --- данные и поиск ---------------------------------------------------
    c = []
    add = c.append

    add("// Сгенерировано tools/make_font.py - НЕ ПРАВИТЬ ВРУЧНУЮ.")
    add("//")
    add("// Три таблицы вместо одной: ASCII и кириллица занимают непрерывные")
    add("// блоки кодов, поэтому ищутся вычитанием, а Ё и ё стоят вне блока и")
    add("// лежат отдельными строками. Один общий массив потребовал бы поиска")
    add("// по 161 элементу на каждый символ.")
    add("")
    add('#include "font_5x7.h"')
    add("")
    add("#include <stddef.h>")
    add("")
    emit_table(add, "kAscii", GLYPHS, ascii_codes)
    emit_table(add, "kCyr", CYR_GLYPHS, cyr_codes)
    emit_table(add, "kYoUpper", YO_GLYPHS, [YO_UPPER])
    emit_table(add, "kYoLower", YO_GLYPHS, [YO_LOWER])

    add("const uint8_t* font_glyph(uint32_t cp)")
    add("{")
    add("    if (cp >= FONT_ASCII_FIRST && cp <= FONT_ASCII_LAST) {")
    add("        return kAscii[cp - FONT_ASCII_FIRST];")
    add("    }")
    add("    if (cp >= FONT_CYR_FIRST && cp <= FONT_CYR_LAST) {")
    add("        return kCyr[cp - FONT_CYR_FIRST];")
    add("    }")
    add(f"    if (cp == 0x{YO_UPPER:04X}) {{")
    add("        return kYoUpper[0];")
    add("    }")
    add(f"    if (cp == 0x{YO_LOWER:04X}) {{")
    add("        return kYoLower[0];")
    add("    }")
    add("    return NULL;")
    add("}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    OUT_H.write_text("\n".join(h) + "\n", encoding="utf-8")
    OUT_C.write_text("\n".join(c) + "\n", encoding="utf-8")

    size = total * GLYPH_H
    print(f"{total} глифов ({len(GLYPHS)} ASCII + {len(CYR_GLYPHS)} кириллица"
          f" + {len(YO_GLYPHS)} Ё/ё), {GLYPH_W}x{GLYPH_H}, {size} Б данных")
    print(f"готово: {OUT_H}")
    print(f"готово: {OUT_C}")


if __name__ == "__main__":
    main()
