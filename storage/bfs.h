// Своя файловая система во встроенном flash: BFS.
//
// Почему своя, а не FAT/SPIFFS/LittleFS из IDF. Все три приходят через
// esp_partition, а он читает таблицу разделов через spi_flash_mmap; mmap
// требует замков, которые заводит esp_flash_app_init, то есть FreeRTOS.
// Планировщика у нас нет (JOURNAL от 06.11.2026, запись про драйвер flash).
// Плюс каждая из них тянет свой слой блочного устройства, свои настройки и
// свою отладку - а формат, который написан здесь, можно проверить на маке,
// разобрать по байтам с дампа flash и починить, когда плата не отвечает.
//
// Как устроена целостность: копирование при записи (COW), без журнала.
// Блоки метаданных никогда не переписываются на месте. Изменение - это новые
// блоки плюс новый суперблок, который на них указывает. Пока суперблок не
// записан, на диске лежит прежнее состояние, и оно целое. Отсюда два
// следствия, ради которых всё и затевалось:
//
//   - крах в любой момент времени откатывает ФС к предыдущему коммиту;
//   - монтирование ничего не пишет, только читает. Ошибка в нём не может
//     испортить данные, а сам код неудобно проверять: он работает лишь после
//     краха. У журнала (WAL) пришлось бы писать replay при каждом монтировании.
//
// Цена: каждый новый блок требует стирания сектора (45 мс по замерам). Но при
// записи данных стирание неизбежно в любом случае - NOR-flash не пишет поверх
// нестёртого. COW его не добавляет, а только делает явным.
//
// Раскладка раздела (блок = сектор = 4 КБ):
//
//   блок 0, 1      суперблок: два сектора, в каждом 32 слота по 128 байт
//   блоки 2..9     inode-таблица: 8 блоков по 32 inode = 256 inode
//   остальное      данные, каталоги, indirect-блоки
//
// Блоки inode-таблицы - только начальное размещение: таблица тоже пишется
// через COW, поэтому её актуальные номера лежат в суперблоке и меняются при
// каждом изменении любого inode.
//
// Суперблок пишется кольцом по 32 слота в секторе, затем сектор меняется и
// стирается. Два сектора нужны именно из-за стирания: пока стирается один,
// второй держит последнюю живую копию. Стирание - раз в 32 коммита вместо
// каждого.
//
// Битмап занятых блоков на диске НЕ хранится: он собирается при монтировании
// обходом inode-таблицы. Расходиться с деревом ему просто не с чем, а
// монтирование остаётся только читающим.
//
// Чего здесь сознательно нет в первой версии: прав и владельцев (пользователей
// в системе нет), ссылок (symlink/hardlink), контрольных сумм содержимого
// файлов (только у суперблока).
//
// Время изменения (mtime) есть, но часы сюда не заходят. Поле лежит в inode и
// заполняется значением, которое дал вызывающий через bfs_set_now: у ФС нет
// своего источника времени, и заводить его внутри значило бы, что формат
// зависит от того, умеет ли плата читать RTC. Старые образы при этом читаются
// без правок - там в поле ноль, и это честно означает «время неизвестно»,
// а не 1 января 1970-го.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Блок = сектор стирания. 4 КБ - не выбор, а свойство чипа (`env:flash`,
// docs/board.md §6): стирать блоками другого размера он не умеет.
#define BFS_BLOCK_SIZE 4096u

// Длина имени без нуля. 32-байтная запись каталога: inode(4) + тип(2) +
// длина(1) + резерв(1) + имя(24). Ровно 128 записей в блоке, и запись никогда
// не пересекает границу блока - на этом держится обход каталога по блокам.
#define BFS_NAME_MAX 24u

#define BFS_INODE_SIZE        128u
#define BFS_INODES_PER_BLOCK  (BFS_BLOCK_SIZE / BFS_INODE_SIZE)
#define BFS_INODE_COUNT       256u
#define BFS_INODE_BLOCKS     (BFS_INODE_COUNT / BFS_INODES_PER_BLOCK)

// 12 прямых блоков - 48 КБ без косвенности. Дальше indirect на 1024 блока
// (4 МБ) и double indirect. Double нужен не «на всякий случай»: раздел 14 МБ,
// и один большой файл в него должен помещаться целиком.
#define BFS_DIRECT_BLOCKS 12u
#define BFS_PTRS_PER_BLOCK (BFS_BLOCK_SIZE / 4u)

#define BFS_SUPER_SLOTS   32u
#define BFS_SUPER_SLOT    128u
#define BFS_SUPER_SECTORS 2u

// Верхняя граница раздела, под который рассчитан битмап: 4096 блоков = 16 МБ.
// Больше физического flash на этой плате не бывает, а битмап тогда занимает
// ровно 512 байт и лежит в структуре, без выделения памяти.
#define BFS_MAX_BLOCKS 4096u

// Тип узла. Младшие 12 бит mode - тип (как в POSIX), остальное свободно.
#define BFS_TYPE_FILE 0x8000u
#define BFS_TYPE_DIR  0x4000u
#define BFS_TYPE_MASK 0xF000u

#define BFS_ROOT_INODE 1u

// Коды возврата. Свои, а не esp_err_t: модуль переносимый и на маке esp_err_t
// нет. Ноль - успех, всё остальное отрицательное, чтобы `if (rc)` читалось.
enum {
    BFS_OK = 0,
    BFS_ERR_IO = -1,        // отказ устройства; ФС помечена сломанной
    BFS_ERR_FORMAT = -2,    // это не BFS или суперблок повреждён
    BFS_ERR_NO_SPACE = -3,  // кончились блоки или inode
    BFS_ERR_NOT_FOUND = -4,
    BFS_ERR_EXISTS = -5,
    BFS_ERR_NOT_DIR = -6,
    BFS_ERR_IS_DIR = -7,
    BFS_ERR_NOT_EMPTY = -8,
    BFS_ERR_NAME = -9,      // пустое имя, слишком длинное или негодный путь
    BFS_ERR_ARG = -10,
    BFS_ERR_BROKEN = -11,   // ФС уже сломана прошлой ошибкой, нужен remount
};

// Блочное устройство. Смещения - в байтах от начала раздела, а не номера
// блоков: суперблок пишется по 128 байт внутри сектора, и блочный интерфейс
// этого не умеет. Заодно совпадает с basalt_flash_read/write, у которых
// аргумент - адрес и длина.
//
// erase стирает сектор, содержащий offset; offset обязан быть выровнен по
// BFS_BLOCK_SIZE. Возврат: 0 - успех, не ноль - ошибка (код не разбирается).
typedef struct bfs_device {
    void* ctx;
    int (*read)(void* ctx, uint32_t offset, void* dst, uint32_t len);
    int (*erase)(void* ctx, uint32_t offset);
    int (*write)(void* ctx, uint32_t offset, const void* src, uint32_t len);
} bfs_device_t;

// Состояние монтирования. Всё, что нужно между вызовами: устройство, битмап и
// указатели на метаданные. Битмап в памяти, а не на диске, - см. шапку файла.
typedef struct bfs {
    bfs_device_t dev;
    uint32_t block_count;
    uint32_t generation;
    uint32_t super_slot;  // следующий слот кольца (0..2*BFS_SUPER_SLOTS-1)
    uint32_t inode_table[BFS_INODE_BLOCKS];
    uint32_t root_inode;

    // Занятые блоки. Отдельный pending: блок, освобождённый в текущей
    // транзакции, нельзя отдать под новую запись, пока коммит не записан, -
    // на диске ещё лежит суперблок, который на него ссылается. Поэтому
    // освобождение откладывается до коммита.
    uint8_t bitmap[BFS_MAX_BLOCKS / 8];
    uint8_t pending[BFS_MAX_BLOCKS / 8];

    bool mounted;
    bool broken;
    bool dirty;  // были изменения с прошлого коммита

    // Текущее время для новых меток. Выставляется снаружи (bfs_set_now) и
    // только читается: ФС не имеет своих часов. Ноль означает «часы не
    // установлены», и тогда mtime у новых файлов остаётся нулевым - так
    // `ls -l` отличает «время неизвестно» от «создан в 1970-м».
    uint32_t now;
} bfs_t;

// Разметить раздел заново: стереть суперблок, создать пустой корень.
// Существующие данные теряются, и это не проверяется - решение принимает
// вызывающий.
int bfs_format(bfs_t* fs, const bfs_device_t* dev, uint32_t block_count);

// Размер файла, его тип и время изменения (секунды Unix; 0 - неизвестно).
typedef struct {
    uint32_t size;
    uint32_t mtime;
    uint16_t type;  // BFS_TYPE_FILE / BFS_TYPE_DIR
} bfs_stat_t;

// Прочитать суперблок и собрать битмап. Ничего не пишет.
// BFS_ERR_FORMAT - раздел не размечен или суперблок не сошёлся по CRC.
int bfs_mount(bfs_t* fs, const bfs_device_t* dev);

// Время, которым помечаются изменения с этого момента. ФС не читает часы
// сама: значение даёт вызывающий, и только оно попадает в inode. Ноль -
// «время неизвестно», и новые файлы останутся без метки.
void bfs_set_now(bfs_t* fs, uint32_t unix_secs);

// Размер, тип и время изменения. out может быть NULL - тогда функция только
// проверяет, что узел существует.
int bfs_stat(bfs_t* fs, const char* path, bfs_stat_t* out);

// Создать пустой файл. BFS_ERR_EXISTS, если имя занято.
int bfs_create(bfs_t* fs, const char* path);

// Создать каталог.
int bfs_mkdir(bfs_t* fs, const char* path);

// Удалить файл. Освобождение блоков откладывается до коммита.
int bfs_unlink(bfs_t* fs, const char* path);

// Удалить пустой каталог.
int bfs_rmdir(bfs_t* fs, const char* path);

// Переименовать внутри одного каталога и между каталогами.
int bfs_rename(bfs_t* fs, const char* from, const char* to);

// Изменить размер файла. Уменьшение освобождает блоки, увеличение читает
// дырку нулями (стёртая flash - 0xFF, поэтому «нет блока» и «нули» - разное).
int bfs_truncate(bfs_t* fs, const char* path, uint32_t size);

// Чтение и запись по смещению. *done - сколько байт удалось (может быть
// меньше при ошибке или конце файла), допускает NULL.
int bfs_read(bfs_t* fs, const char* path, uint32_t offset, void* dst, uint32_t len,
             uint32_t* done);
int bfs_write(bfs_t* fs, const char* path, uint32_t offset, const void* src, uint32_t len,
              uint32_t* done);

// Перебор каталога: index - номер живого элемента с нуля. Имя копируется в
// name размером не меньше BFS_NAME_MAX + 1. out может быть NULL. Когда
// элементы кончились - BFS_ERR_NOT_FOUND, и вызывающий этим и останавливается.
int bfs_readdir(bfs_t* fs, const char* path, uint32_t index, char* name, bfs_stat_t* out);

// Сколько блоков занято и сколько всего - для `df` и для щупа.
int bfs_usage(const bfs_t* fs, uint32_t* used, uint32_t* total);
