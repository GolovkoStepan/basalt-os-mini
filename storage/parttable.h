// Разбор таблицы разделов flash: записи по 32 байта с 0x8000.
//
// Зачем отдельный модуль, а не разбор в том, кому он нужен. Таблицу будут
// читать двое: щуп env:flash (показать, что на чипе на самом деле) и файловая
// система (найти раздел storage). Формат при этом один и не наш - он описан в
// IDF (esp_partition.h, gen_esp32part.py), и ошибиться в нём легко: неверное
// смещение поля даёт не отказ, а раздел с мусорным адресом.
//
// Почему разбор отдельно от чтения flash. Здесь только байты, которые уже
// лежат в памяти: ни регистров, ни esp_flash. Поэтому модуль проверяется на
// маке (test/test_parttable), а не «на плате и повезёт». Чтение таблицы с
// чипа - забота вызывающего: у щупа это один basalt_flash_read, у ФС будет
// тот же.
//
// Почему не esp_partition_*. Готовый слой читает таблицу через
// spi_flash_mmap, а mmap требует замков, которые заводит esp_flash_app_init -
// то есть планировщика FreeRTOS. При своём старте его нет (JOURNAL от
// 06.11.2026).

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Длина метки: 16 байт в записи плюс ноль-терминатор. Метка может занимать
// все 16 байт без нуля - тогда в строке будет ровно 16 символов.
#define BASALT_PART_LABEL_MAX 17

// Размер одной записи и её magic. Числа взяты из формата IDF, а не измерены:
// другого источника у таблицы нет.
#define BASALT_PART_ENTRY_SIZE 32
#define BASALT_PART_MAGIC      0x50AA
#define BASALT_PART_MAGIC_MD5  0xEBEB

// Результат чтения одной записи.
typedef enum {
    BASALT_PART_OK = 0,
    // Записей больше нет: стёртая flash. Это нормальный конец таблицы, а не
    // ошибка - таблица не обязана занимать весь сектор.
    BASALT_PART_END_FF,
    // Конец записей - контрольная сумма MD5. Тоже норма: gen_esp32part.py
    // всегда дописывает её последней.
    BASALT_PART_END_MD5,
    // На месте таблицы не таблица: чужой magic. Значит, читали не оттуда или
    // таблицу никогда не заливали.
    BASALT_PART_BAD_MAGIC,
    // Аргументы не годятся: NULL или длина меньше одной записи.
    BASALT_PART_BAD_ARG,
} basalt_part_status_t;

// Одна запись таблицы.
typedef struct {
    uint32_t address;  // смещение в flash, байт
    uint32_t size;     // размер, байт
    uint8_t type;      // 0 - приложение, 1 - данные (esp_partition.h)
    uint8_t subtype;   // 2 - nvs, 1 - phy, 0x40 - свой формат
    char label[BASALT_PART_LABEL_MAX];
} basalt_partition_t;

// Прочитать запись с номером index (с нуля) из буфера table длиной length.
//
// Буфер - это то, что прочитано с адреса таблицы; сколько байт читать, решает
// вызывающий (у IDF таблица занимает один сектор, 0xC00 значащих байт).
// Запись, вылезшая за length, считается отсутствующей: длина меньше одной
// записи - это не таблица.
basalt_part_status_t basalt_parttable_get(const uint8_t* table, size_t length, unsigned index,
                                          basalt_partition_t* out);

// Найти раздел по метке. true - найден и записан в out.
//
// Поиск по метке, а не по номеру записи: порядок разделов в таблице - не
// контракт, его меняют при переразметке, а имя раздела остаётся.
bool basalt_parttable_find(const uint8_t* table, size_t length, const char* label,
                           basalt_partition_t* out);
