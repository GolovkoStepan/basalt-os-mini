// VFS: имена и текущий каталог над конкретными файловыми системами.
//
// Зачем слой, если ФС одна. Во-первых, «/» - это точка монтирования, а не
// синоним BFS: в плане есть /tmp (ramdisk в SRAM) и /dev (таблица устройств),
// и когда они появятся, вызывающий код не должен узнать об этом ни строчкой.
// Во-вторых, у BFS нет `..`: у inode нет ссылки на родителя, и хранить её -
// лишняя запись при каждом переименовании. Значит, путь обязан кто-то
// разбирать, и это место - здесь, а не в шелле: иначе каждый, кто открывает
// файл, будет повторять разбор по-своему.
//
// Что здесь есть и чего нет. Здесь: канонизация пути (`.`, `..`, `//`),
// таблица точек монтирования, текущий каталог и таблица открытых файлов.
// Здесь нет: прав и владельцев (пользователей в системе нет), символьных
// ссылок, блокировок и буферизации - всё это либо не нужно, либо принадлежит
// конкретной ФС.
//
// Почему таблица открытых файлов всё-таки есть, хотя планировщика нет.
// Открытый файл - это имя плюс позиция чтения; без позиции `cat` пришлось бы
// каждый раз передавать смещение, и «прочитать файл целиком» стало бы делом
// вызывающего. Владелец записи в таблице сейчас один - оболочка: она открывает
// файл, читает и закрывает в пределах одной команды. Утечка fd здесь была бы
// видна сразу (кончились слоты), а не через неделю.
//
// Цена решения: интерфейс бэкенда повторяет операции ФС, то есть при появлении
// второй ФС нужно будет написать адаптер на десяток функций. Это дешевле, чем
// обнаружить, что ramdisk в /tmp не влезает в интерфейс, заточенный под BFS.

#pragma once

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// Предел длины пути в пространстве имён VFS. Меньше, чем BFS_PATH_MAX (256):
// глубже десятка каталогов по 24 символа всё равно не уложиться в экран, а
// каждый открытый файл хранит свой путь целиком.
#define VFS_PATH_MAX  128u

// Имя в каталоге без нуля. Бэкенд обязан не отдавать длиннее: буфер
// вызывающего - VFS_NAME_MAX + 1 байт.
#define VFS_NAME_MAX  32u

// Сколько точек монтирования и открытых файлов бывает одновременно. Числа
// маленькие и фиксированные: память под них статическая, а не из кучи, и
// ошибка «забыли закрыть» видна как «кончились слоты».
#define VFS_MOUNT_MAX 4u
#define VFS_OPEN_MAX  8u

// Тип узла. Значения совпадают с BFS сознательно: это общепринятые в POSIX
// биты типа, и переводить 0x8000 в какое-то своё число значило бы завести
// третий словарь. Совпадение не даёт права передавать значение напрямую -
// адаптер всё равно переводит явно, чтобы граница была видна.
#define VFS_TYPE_FILE 0x8000u
#define VFS_TYPE_DIR  0x4000u

// Коды возврата. Ноль - успех, остальное отрицательное: `if (rc)` читается
// без сравнения с нулём.
enum {
    VFS_OK = 0,
    VFS_ERR_IO = -1,         // отказ устройства
    VFS_ERR_FORMAT = -2,     // раздел не размечен
    VFS_ERR_NO_SPACE = -3,
    VFS_ERR_NOT_FOUND = -4,
    VFS_ERR_EXISTS = -5,
    VFS_ERR_NOT_DIR = -6,
    VFS_ERR_IS_DIR = -7,
    VFS_ERR_NOT_EMPTY = -8,
    VFS_ERR_NAME = -9,       // пустое, слишком длинное имя или негодный путь
    VFS_ERR_ARG = -10,
    VFS_ERR_NO_MOUNT = -12,  // этот путь не принадлежит ни одной точке
    VFS_ERR_NO_FD = -13,     // кончились слоты таблицы открытых файлов
    VFS_ERR_BAD_FD = -14,
};

// Флаги открытия. Прав нет, поэтому VFS_O_WRONLY ни на что не влияет: он
// остаётся ради интерфейса, который не придётся менять, когда права появятся.
#define VFS_O_RDONLY 0x00u
#define VFS_O_WRONLY 0x01u
#define VFS_O_CREATE 0x02u
#define VFS_O_TRUNC  0x04u
#define VFS_O_APPEND 0x08u

typedef struct {
    uint32_t size;
    uint32_t mtime;  // секунды Unix; 0 - неизвестно
    uint16_t type;   // VFS_TYPE_FILE / VFS_TYPE_DIR
} vfs_stat_t;

// Операции конкретной ФС. Пути - абсолютные внутри своей точки монтирования
// и уже канонизированные: `..` сюда не доходит никогда, поэтому бэкенду не
// нужно уметь ходить вверх.
//
// Возврат - коды VFS_*, а не свои: адаптер переводит их явно (см. vfs_bfs.c).
// usage может быть NULL - тогда df на этой точке не работает. Единица
// измерения - байты: у ФС бывают блоки разного размера, и пересчёт в байты
// на границе избавляет оболочку от знания чужого формата.
typedef struct vfs_backend {
    void* ctx;
    int (*stat)(void* ctx, const char* path, vfs_stat_t* out);
    int (*create)(void* ctx, const char* path);
    int (*mkdir)(void* ctx, const char* path);
    int (*unlink)(void* ctx, const char* path);
    int (*rmdir)(void* ctx, const char* path);
    int (*rename)(void* ctx, const char* from, const char* to);
    int (*readdir)(void* ctx, const char* path, uint32_t index, char* name, vfs_stat_t* out);
    int (*read)(void* ctx, const char* path, uint32_t offset, void* dst, uint32_t len,
                uint32_t* done);
    int (*write)(void* ctx, const char* path, uint32_t offset, const void* src, uint32_t len,
                 uint32_t* done);
    int (*truncate)(void* ctx, const char* path, uint32_t size);
    int (*usage)(void* ctx, uint32_t* used, uint32_t* total);
    // Необязательный: у ФС с метками времени - «который сейчас час». Время
    // даёт вызывающий, ФС часов не читает (см. bfs_set_now). NULL - у этой
    // точки монтирования меток нет, и vfs_set_now её просто пропускает.
    void (*set_now)(void* ctx, uint32_t unix_secs);
} vfs_backend_t;

// Сбросить таблицу монтирования и текущий каталог в "/". Нужно и при старте,
// и перед каждым тестом: состояние модуля статическое.
void vfs_init(void);

// Смонтировать бэкенд в точку prefix ("/" или "/tmp"). Структура копируется,
// поэтому вызывающий может держать её где угодно. Префикс копируется тоже:
// строка на стеке вызывающего после возврата уже не наша забота.
//
// Вложенные точки разрешены (в этом и смысл префикса), но вторая точка с тем
// же префиксом - нет: это было бы «смонтировать поверх», а размонтирования в
// интерфейсе нет.
int vfs_mount(const char* prefix, const vfs_backend_t* backend);

// Есть ли хоть одна смонтированная точка.
bool vfs_mounted(void);

// Привести путь к абсолютному каноническому виду относительно cwd.
//
// Правила: пустой путь - ошибка; относительный считается от cwd; `.`
// выбрасывается; `..` откуда угодно ведёт в корень (выше корня некуда);
// повторные '/' и хвостовой '/' убираются; результат всегда начинается с '/'.
//
// Функция вынесена наружу и ничего не знает про монтирование: это чистая
// логика, и именно её проверяют тесты на маке гуще всего - ошибка в разборе
// пути видна как «файл не найден» через месяц.
int vfs_normalize(const char* cwd, const char* path, char* out, size_t out_size);

// То же, но относительно текущего каталога.
int vfs_resolve(const char* path, char* out, size_t out_size);

int vfs_chdir(const char* path);
const char* vfs_cwd(void);
int vfs_getcwd(char* out, size_t out_size);

// Операции над путём. Все принимают относительный или абсолютный путь.
int vfs_stat(const char* path, vfs_stat_t* out);
int vfs_mkdir(const char* path);
int vfs_unlink(const char* path);
int vfs_rmdir(const char* path);
int vfs_rename(const char* from, const char* to);
// Обрезать файл до size байт. Отдельно от vfs_open, потому что усечение иногда
// нужно отложить: оболочка открывает `> f` раньше, чем поймёт, что читает тот
// же самый файл, и немедленный O_TRUNC уничтожил бы данные.
int vfs_truncate(const char* path, uint32_t size);
int vfs_readdir(const char* path, uint32_t index, char* name, vfs_stat_t* out);
// Занято и всего, в байтах.
int vfs_usage(const char* path, uint32_t* used, uint32_t* total);
// Время для новых меток на всех точках монтирования. Секунды Unix, 0 -
// «часы не установлены». Вызывается, когда время меняется: при старте (когда
// прочитан /etc/clock) и командой `date set`.
void vfs_set_now(uint32_t unix_secs);

// Открытые файлы. fd - индекс в таблице; закрывать обязательно, слотов восемь.
int vfs_open(const char* path, uint8_t flags, int* fd);
int vfs_read(int fd, void* dst, uint32_t len, uint32_t* done);
int vfs_write(int fd, const void* src, uint32_t len, uint32_t* done);
int vfs_seek(int fd, uint32_t offset);
uint32_t vfs_tell(int fd);
int vfs_close(int fd);

// Текст ошибки по-русски - для оболочки. Возвращает всегда непустую строку,
// в том числе на незнакомый код: печатать «ошибка -37» без объяснения хуже,
// чем напечатать «неизвестная ошибка -37».
const char* vfs_strerror(int rc);
