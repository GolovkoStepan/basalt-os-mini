// Привязка BFS к разделу встроенного flash.
//
// Зачем отдельный модуль. Одна и та же работа нужна двум местам: щупу env:fs
// (проверить ФС на железе) и оболочке (смонтировать корень при старте). Это
// поиск раздела по метке, проверка выравнивания и границ, адаптер блочного
// устройства поверх драйвера flash и разметка, если раздел пуст. Второй копии
// здесь быть не должно: разъедутся - и «работает в щупе» перестанет значить
// «работает в системе».
//
// Почему не в arch/: там драйвер flash, то есть слой чипа. Здесь - знание про
// разделы и про то, что в них лежит ФС; это уровень хранилища, а не платформы.
// Поэтому файл живёт в storage/ рядом с bfs.c и parttable.c.
//
// Почему не в хостовых тестах: работает он с настоящим flash (basalt_flash_*),
// а подменять драйвер заглушкой ради проверки четырёх проверок границ дороже,
// чем проверить это на плате. Логика, у которой есть что проверять на маке
// (разбор таблицы, сам формат), лежит в parttable.c и bfs.c и проверяется там.

#pragma once

#include <stdbool.h>

#include "bfs.h"

// Свои коды поверх кодов BFS: то, что происходит до монтирования, к формату
// файловой системы отношения не имеет.
enum {
    // Драйвер flash не завёлся - проверять нечего.
    BASALT_FS_ERR_NO_FLASH = -20,
    // В таблице разделов нет раздела с такой меткой.
    BASALT_FS_ERR_NO_PARTITION = -21,
    // Раздел есть, но в него нельзя: не выровнен по сектору или не того
    // размера для битмапа BFS.
    BASALT_FS_ERR_BAD_PARTITION = -22,
};

// Смонтировать раздел label как BFS.
//
// format_if_empty - разметить, если раздел ещё не размечен. Решение принимает
// вызывающий: у щупа это норма, а у системы «разметить и потерять файлы»
// должно быть осознанным действием, а не побочным эффектом монтирования.
// formatted (может быть NULL) - была ли разметка; нужно отчёту.
//
// Возврат: 0 или отрицательный код (BFS_* / BASALT_FS_ERR_*).
int basalt_fs_mount(bfs_t* fs, const char* label, bool format_if_empty, bool* formatted);

// Разметить раздел заново, не спрашивая. Данные теряются.
int basalt_fs_format(bfs_t* fs, const char* label);

// Найти раздел по метке в таблице разделов на чипе. Нужно отчётам (адрес и
// размер), чтобы не повторять чтение таблицы в каждом.
int basalt_fs_partition(const char* label, uint32_t* address, uint32_t* size);
